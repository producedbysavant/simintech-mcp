"""Промпты: готовые сценарии сборки модели для клиента.

Текст промпта — вторая копия контракта инструментов: классы блоков и имена
их параметров здесь должны совпадать с каталогом
(`simintech_api/data/block_catalog.json`). Проверяется это содержимое, а не
факт регистрации, — см. `tests/unit/test_prompts.py`.
"""

from __future__ import annotations

from .app import mcp


# ─── Промпты (шаблоны) ────────────────────────────────────────────

@mcp.prompt()
def create_pid_model(kp: float = 1.0, ki: float = 0.5,
                     kd: float = 0.1, setpoint: float = 1.0) -> str:
    """Шаблон создания ПИД-регулятора в SimInTech.

    Возвращает последовательность команд для сборки ПИД-контура
    с обратной связью через инструменты MCP-сервера.

    Ветви собираются по схеме из `examples/pid_controller.py` (simintech-code):
    ошибка = уставка − обратная связь; P — «Усилитель» kp; I — «Интегратор» +
    «Усилитель» ki; D — «Производная» + «Усилитель» kd; сумма ветвей —
    «Сумматор» на три входа. Без «Производной» контур не ПИД, и отличить это
    по расчёту нельзя — он идёт так же.

    Args:
        kp, ki, kd: коэффициенты ПИД-регулятора.
        setpoint: уставка (значение ступеньки).
    """
    return (
        f"Создай ПИД-регулятор в SimInTech: ошибка — расхождение задания и "
        f"обратной связи, ветви P, I и D складываются.\n"
        f"1. create_project(project_hint=\"pid\", end_time=20)\n"
        f"2. add_block(class_name=\"Ступенька\", props=\"yk={setpoint}\")"
        f"  # задание\n"
        f"3. add_block(class_name=\"Сумматор\", props=\"a=[1.0,-1.0]\")"
        f"  # ошибка e = задание - обратная связь\n"
        f"4. add_block(class_name=\"Усилитель\", props=\"a={kp}\")"
        f"  # P-ветвь\n"
        f"5. add_block(class_name=\"Интегратор\", props=\"k=1.0,x0=0.0\")"
        f"  # I-ветвь: интегрирует ошибку\n"
        f"6. add_block(class_name=\"Усилитель\", props=\"a={ki}\")"
        f"  # I-ветвь: коэффициент ki\n"
        f"7. add_block(class_name=\"Производная\", props=\"x0=0.0\")"
        f"  # D-ветвь: дифференцирует ошибку\n"
        f"8. add_block(class_name=\"Усилитель\", props=\"a={kd}\")"
        f"  # D-ветвь: коэффициент kd\n"
        f"9. add_block(class_name=\"Сумматор\", in_ports=3, "
        f"props=\"a=[1.0,1.0,1.0]\")  # сумма P + I + D\n"
        f"10. Соедини по фактическим именам блоков из ответов add_block "
        f"(in_index — номер входа в connect):\n"
        f"    Ступенька → Сумматор(e, in_index=0)\n"
        f"    Сумматор(e) → Усилитель(kp)\n"
        f"    Сумматор(e) → Интегратор\n"
        f"    Интегратор → Усилитель(ki)\n"
        f"    Сумматор(e) → Производная\n"
        f"    Производная → Усилитель(kd)\n"
        f"    Усилитель(kp) → Сумматор(сумма, in_index=0)\n"
        f"    Усилитель(ki) → Сумматор(сумма, in_index=1)\n"
        f"    Усилитель(kd) → Сумматор(сумма, in_index=2)\n"
        f"    Сумматор(сумма) → Сумматор(e, in_index=1)  # обратная связь\n"
        f"11. layout_place по фактическим именам блоков\n"
        f"12. run(to_time=20) и проверь get_time() в ответе\n"
        f"\n"
        f"Блоки НЕ переименовываются: `name_hint` не применяется, а "
        f"фактические имена (`k_0`, `kx_0`, …) возвращает add_block — по ним "
        f"и соединяй.\n"
        f"Соедини ВСЕ входы: блок с висящим входом молча останавливает "
        f"расчёт.\n"
    )


@mcp.prompt()
def create_rc_chain(rc: float = 1.0, amplitude: float = 5.0) -> str:
    """Шаблон создания RC-цепи (апериодическое звено 1/(RC·s+1)).

    Усилитель 1/RC и интегратор охвачены обратной связью по выходу: без неё
    цепочка «усилитель → интегратор» даёт линейно растущий выход (u·t/RC), а
    не инерционное звено, — и по расчёту это не диагностируется.
    """
    return (
        f"Создай RC-цепь в SimInTech — апериодическое звено 1/(RC·s+1):\n"
        f"1. create_project(project_hint=\"rc\", end_time={5.0 * rc})\n"
        f"2. add_block(class_name=\"Ступенька\", props=\"yk={amplitude}\")"
        f"  # вход u\n"
        f"3. add_block(class_name=\"Сумматор\", props=\"a=[1.0,-1.0]\")"
        f"  # u - y\n"
        f"4. add_block(class_name=\"Усилитель\", "
        f"props=\"a={_gain_for_rc(rc)}\")  # 1/RC\n"
        f"5. add_block(class_name=\"Интегратор\", props=\"k=1.0,x0=0.0\")\n"
        f"6. Соедини по фактическим именам блоков из ответов add_block:\n"
        f"    Ступенька → Сумматор(u - y, in_index=0)\n"
        f"    Сумматор(u - y) → Усилитель\n"
        f"    Усилитель → Интегратор\n"
        f"    Интегратор → Сумматор(u - y, in_index=1)  # обратная связь\n"
        f"7. layout_place по фактическим именам блоков\n"
        f"8. run(to_time={5.0 * rc}) и проверь get_time() в ответе\n"
        f"\n"
        f"Обратная связь обязательна: без неё усилитель и интегратор дают "
        f"линейно растущий выход, а не 1/(RC·s+1).\n"
        f"Переименование через COM недоступно — используй автоимена.\n"
    )


# ─── Внутреннее ───────────────────────────────────────────────────

def _gain_for_rc(rc: float) -> float:
    """Коэффициент усилителя для RC-цепи: 1/RC (защита от деления на 0)."""
    return 1.0 / rc if rc else 1.0
