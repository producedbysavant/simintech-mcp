def _ensure_pack() -> Pack:
    """Текущий пакет сессии — с проверкой, что COM ещё отвечает.

    Пробник тот же, что в `_ensure_project` (`GetProcessID`), и нужен по той
    же причине: флаг `connected` переживает смерть `mmain.exe`, а пакет держит
    тот же мёртвый прокси. Мёртвый клиент сбрасывает сессию вместе с пакетом;
    отказ называет это, а не только «пакета нет»: клиент иначе решил бы, что
    пакет не открывали.
    """
    if _client is not None and not _client_is_alive(_client):
        _drop_dead_session()
        raise ToolError(
            "Соединение с SimInTech потеряно: mmain.exe не отвечает (пробный "
            "COM-вызов не прошёл). Состояние сессии сброшено — пакет и "
            "текущий проект закрыты. Перезапустите mmain.exe и откройте пакет "
            "заново (`open_pack`): повторять вызов без этого бессмысленно.")
    if _pack is None:
        raise ToolError("Нет открытого пакета. Сначала вызовите open_pack")
    return _pack


def _set_pack(pack: Optional[Pack], source_path: Optional[str] = None) -> None:
    """Сделать пакет текущим — единственное место, где он меняется.

    Линии пакет не трогает: они принадлежат текущему проекту, и смена проекта
    происходит не здесь (см. `_set_project`). А вот текущий проект пакет
    уносит с собой: его участники закрываются вместе с пакетом (живой замер
    01.10.2026), поэтому вызывающий обязан до или после смены позаботиться о
    `_set_project(None)`, если текущий проект был участником, — за него это
    делают `_replace_pack` и инструменты пакета.
    """
    global _pack, _pack_path
    _pack = pack
    _pack_path = source_path


def _pack_label() -> str:
    """Имя текущего пакета для ответов: «Пакет.pak» (id=…); пусто — пакета нет."""
    if _pack is None:
        return ""
    name = (os.path.basename(_pack_path.replace("\\", "/"))
            if _pack_path else "пакет")
    return f"«{name}» (id={_pack.id})"


def _pack_member_ids() -> Optional[List[int]]:
    """Идентификаторы участников текущего пакета.

    `None` — состав прочитать не удалось: идентификаторы участников среда
    выдаёт заново после изменений состава (замер 01.10.2026), и запрос к
    подпорченному пакету может отказать. Отличить «не участник» от «не смогли
    прочитать» важно: на первом строится защита участника в `_replace_project`,
    и молчаливое «пусто» закрыло бы участника, исключив его из пакета.
    Сбой чтения других путей не ломает — вызывающие трактуют `None` как
    «неизвестно».
    """
    if _pack is None:
        return []
    try:
        return list(_pack.project_ids())
    except Exception:                                         # noqa: BLE001
        return None


def _pack_membership() -> Optional[bool]:
    """Участие текущего проекта в открытом пакете сессии: True / False / None.

    `None` — состав пакета прочитать не удалось, и «участник» от «не
    участник» отличить нечем. Вызывающие обязаны трактовать `None` как
    «нельзя исключить» (fail-closed): закрывающие операции над таким проектом
    не выполняются — `CloseProject` участника исключает его из состава (замер
    01.10.2026), — а сброс состояния текущего проекта после закрытия пакета
    выполняется: неизвестно, жив ли проект, а мёртвый идентификатор в сессии
    хуже сброшенного. Обычное `bool` здесь означало бы, что сбой чтения
    состава сам отключает защиту — ровно в том случае, ради которого она
    заведена (ревью mcp#25).
    """
    if _pack is None or _project is None:
        return False
    ids = _pack_member_ids()
    if ids is None:
        return None
    return _project.id in ids


def _replace_pack(pack: Pack, source_path: Optional[str] = None) -> str:
    """Сделать пакет текущим, закрыв предыдущий.

    Открытие второго пакета того же файла создаёт **второй** пакет, а не
    возвращает прежний (живой замер 01.10.2026: id другой) — без этого
    закрытия пакеты копились бы в `mmain.exe`, как раньше проекты.

    Если текущий проект — участник закрываемого пакета, он закрывается
    вместе с пакетом, и состояние текущего проекта сбрасывается: иначе сессия
    держала бы проект с мёртвым идентификатором.

    Returns:
        Пустая строка, если менять было нечего; иначе — примечание для ответа:
        смена пакета называется явно, сбой закрытия прежнего — предупреждением.
    """
    previous = _pack
    previous_label = _pack_label()
    membership = _pack_membership() if previous is not None else False
    _set_pack(pack, source_path)
    if previous is None or previous is pack:
        return ""
    switch = (f"\nПАКЕТ СМЕНИЛСЯ: было {previous_label} → "
              f"стало {_pack_label()}.")
    warning = ""
    closed = False
    try:
        previous.close()
        closed = True
    except Exception as exc:                                  # noqa: BLE001
        warning = (f" ВНИМАНИЕ: предыдущий пакет закрыть не удалось "
                   f"({type(exc).__name__}: {exc}) — он мог остаться открытым "
                   f"в SimInTech.")
    # Сброс текущего проекта — только по факту закрытия пакета: уверение
    # «закрыт вместе с пакетом» рядом с предупреждением «пакет закрыть не
    # удалось» — противоречие, и оно уже случалось (ревью mcp#25).
    if closed and membership is not False:
        _set_project(None)
        if membership is None:
            switch += (" Принадлежность текущего проекта к закрытому пакету "
                       "проверить не удалось; текущий проект сброшен на "
                       "всякий случай: текущего проекта больше нет.")
        else:
            switch += (" Текущий проект — участник закрытого пакета — закрыт "
                       "вместе с ним: текущего проекта больше нет.")
    elif not closed and membership is True:
        switch += (" Текущий проект — участник пакета, который закрыть не "
                   "удалось: проект мог остаться открытым вместе с пакетом.")
    return switch + warning
