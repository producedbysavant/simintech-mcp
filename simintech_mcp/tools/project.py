@mcp.tool()
@runtime.com_threaded
def create_project(project_hint: str = "model",
                   end_time: Optional[float] = None) -> str:
    """Создать новый проект SimInTech из шаблона «пустой модели».

    Проект создаётся из шаблона поставки (`Схема модели общего вида.prt`), а не
    через `NewProject`: пустой проект не считает — в нём нет расчётного слоя и
    настроек расчёта, поэтому модельное время не растёт ни через `run`, ни
    через `step`, хотя вызовы и возвращают успех. Особенности среды —
    `simintech-code/docs/reference/com_api_inventory.md`, §18.

    Предыдущий открытый проект закрывается: иначе они копились бы внутри
    `mmain.exe`. Смена текущего проекта называется в ответе явно («было …
    → стало …», issue #18).

    Args:
        project_hint: подсказка для сообщения. Имя проекта задаёт среда,
            переименование через COM недоступно.
        end_time: конечное время расчёта в секундах (> 0); по умолчанию — из
            шаблона (10 с). Меняется инструментом `set_calc_time`.
    """
    # Проверяем до открытия шаблона: иначе неверное значение оставило бы
    # созданный проект висеть в mmain.exe — он не попал бы ни в состояние сессии,
    # ни в закрытие.
    if end_time is not None and end_time <= 0:
        raise ToolError("end_time должен быть положительным числом секунд")

    prj = Project.from_template(session.ensure_client())
    replaced = session.replace_project(prj)
    if end_time is not None:
        prj.set_calc_end_time(end_time)
    tail = (f", время расчёта {end_time} с" if end_time is not None
            else ", время расчёта — из шаблона (10 с)")
    return (f"Проект '{project_hint}' создан из шаблона (id={prj.id}){tail}."
            + replaced)


@mcp.tool()
@runtime.com_threaded(mutates_project=True)
def set_calc_time(seconds: float) -> str:
    """Задать конечное время расчёта проекта (`endtime` расчётного слоя).

    Расчёт идёт до этого момента; `run(to_time=…)` не может уйти за него.

    Args:
        seconds: конечное время расчёта в секундах (> 0).
    """
    session.ensure_project().set_calc_end_time(seconds)
    return f"Время расчёта: {seconds} с"


@mcp.tool()
@runtime.com_threaded
def open_project(path: str) -> str:
    """Открыть существующий проект SimInTech (.prt/.xprt).

    Предыдущий открытый проект закрывается (см. `create_project`), и ответ
    называет это явно: «было … → стало …» — вместе с именем открытого файла.
    Смена текущего проекта — событие сессии, и молчание о ней стоило живой
    ошибки (issue #18: импорт ушёл в проект, снятый ради образца).

    **Путь проверяется до COM.** `OpenProject` на несуществующем пути
    возвращает ненулевой id: среда показывает модальное «Cannot open
    file…», а наружу это не выходит — `GetOpenedFileName` такого проекта
    возвращает **тот же несуществующий путь**, и отличить промах от успеха
    по COM нечем (живой замер 03.10.2026). Без проверки инструмент
    отчитывался бы «Проект открыт», а агент работал бы с пустым
    проектом-фантомом, пока промах не всплывёт в GUI.

    **Путь — абсолютный и полностью определённый.** Относительный проверка
    раскрыла бы от рабочего каталога процесса сервера, а среда раскрывает
    его от своего: на этом они расходятся, и предпроверка либо пропустила
    бы мимо себя чужой файл, либо отказала бы там, где среда открыла бы.
    Тот же расход есть у Windows-пути **без диска** (`\\foo\\m.prt`
    абсолютен, но каждый процесс раскрывает его от своего текущего диска),
    поэтому путь нормализуется, и в COM уходит уже полностью определённый:
    что проверили — то и откроется. Существующий «не-проектный» файл
    (`.mgr` поставки и т.п.) среда отвергает сама — `OpenProject` возвращает
    0, и библиотека отказывает (живой замер 03.10.2026), — поэтому проверки
    существования и абсолютности достаточно.

    Args:
        path: путь к файлу .prt/.xprt (абсолютный, на машине сервера).
    """
    if not os.path.isabs(path):
        raise ToolError(
            f"Путь «{path}» не абсолютный: относительный раскрывался бы от "
            f"рабочего каталога процесса сервера, а среда раскрывает его от "
            f"своего — на этом они расходятся, и открыться могло бы не то. "
            f"Передайте абсолютный путь (как у `save_project`).")
    path = os.path.abspath(path)
    if not os.path.isfile(path):
        if os.path.isdir(path):
            raise ToolError(
                f"«{path}» — каталог, а не файл проекта. Укажите путь к "
                f"файлу .prt/.xprt: проекты поставки часто лежат в "
                f"одноимённом каталоге, и его легко перепутать с файлом.")
        raise ToolError(
            f"Файл не найден: «{path}». Проверьте путь — файл должен "
            f"существовать на машине сервера (среда на такой вызов "
            f"показывает ошибку, но через COM она не видна, и инструмент "
            f"молча открыл бы пустой проект).")
    prj = Project.open(session.ensure_client(), path)
    replaced = session.replace_project(prj, source_path=path)
    return f"Проект открыт: {session.project_label()}" + replaced


@mcp.tool()
@runtime.com_threaded
def reload_project() -> str:
    """Переоткрыть текущий проект из файла — откат несохранённых правок.

    Закрывает текущий проект **без сохранения** и открывает заново из того же
    файла: правки, не записанные `save_project`, отбрасываются — это тот
    откат, который раньше делали вручную переоткрытием (issue #18). Ответ
    называет прежний и новый экземпляры и говорит, были ли несохранённые
    правки: счёт ведёт сессия — правку помечают мутирующие инструменты
    (их ответы заканчиваются «Не сохранено: …»), снимает `save_project`.

    Отказы называют выход:

    * проект **создан из шаблона** (файла нет) — переоткрывать нечего;
    * текущий проект — **участник пакета**: закрытие исключило бы его из
      состава (живой замер 01.10.2026) — переоткрывается пакет целиком;
    * **файл проекта не найден** — откатывать не к чему (файл мог быть
      удалён или переименован после открытия);
    * **текущего проекта нет** (обычно после перезапуска SimInTech — проект
      не переживает смену инстанса): откатывать нечего — откройте файл
      заново (`open_project`).
    """
    if session.current_project() is None:
        # Отказ приходит ДО `ensure_project`: его текст зовёт к `create_project`
        # и не называет причину — живой случай 04.10.2026: после перезапуска
        # SimInTech сессия отвечала «подключён», а откат выглядел как «проекта
        # не бывало», хотя файл проекта есть. Отката здесь тоже нет, но рецепт
        # другой — открыть файл.
        raise ToolError(
            "Текущего проекта нет — откатывать нечего: reload переоткрывает "
            "уже открытый проект. Обычно это состояние после перезапуска "
            "SimInTech — проект не переживает смену инстанса. Откройте "
            "проект из файла заново (`open_project`).")
    session.ensure_project()
    membership = session.pack_membership()
    if membership is not False:
        if membership is None:
            raise ToolError(
                "Принадлежность текущего проекта к открытому пакету "
                "проверить не удалось (состав пакета не читается): "
                "переоткрывать вслепую нельзя — если проект участник, "
                "закрытие исключит его из состава пакета (живой замер "
                "01.10.2026). Повторите `list_pack_projects`.")
        raise ToolError(
            f"Текущий проект — участник пакета {session.pack_label()}: "
            f"переоткрыть его отдельно нельзя — закрытие исключило бы его "
            f"из состава пакета (живой замер 01.10.2026). Переоткройте пакет "
            f"целиком (`close_pack`, затем `open_pack`) — это откатит всех "
            f"участников.")
    source = session.opened_from()
    if source is None:
        raise ToolError(
            "Текущий проект создан из шаблона (файла нет) — переоткрывать "
            "нечего. Откат без файла: `close_project` и `create_project` "
            "заново.")
    if not source:
        raise ToolError(
            "Источник файла текущего проекта среда не назвала — переоткрыть "
            "нечем. Сохраните проект в файл (`save_project`) и откройте его "
            "(`open_project`).")
    if not os.path.isfile(source):
        raise ToolError(
            f"Файл проекта не найден: «{source}» — переоткатывать не к чему "
            f"(файл мог быть удалён или переименован после открытия). "
            f"Сохраните проект (`save_project`) или откройте другой "
            f"(`open_project`).")
    had_unsaved = session.unsaved_changes()
    prj = Project.open(session.ensure_client(), source)
    replaced = session.replace_project(
        prj, source_path=source,
        header="ТЕКУЩИЙ ПРОЕКТ ПЕРЕОТКРЫТ ИЗ ФАЙЛА")
    tail = (" Несохранённые правки прежнего экземпляра отброшены."
            if had_unsaved else
            " Несохранённых правок не было — файл перечитан как есть.")
    return f"Проект переоткрыт из файла: {source}" + replaced + tail


@mcp.tool()
@runtime.plain_tool
def project_network_role() -> str:
    """Показать роль проекта в распределённом (сетевом) расчёте.

    Роль лежит не в проекте, а рядом с ним — в файле настроек базы сигналов
    `<имя проекта>.dblocalconf` (или `<имя проекта>.dbconf`), и читается без
    COM. Инструмент нужен, чтобы «какой это узел» перестало быть догадкой:
    от роли зависит, кто в сети задаёт модельное время.

    Файл принадлежит не нам: его создаёт SimInTech, и порт приёма данных
    (по умолчанию 19000 — по файлам поставки, в справке этого числа нет)
    поднимается у проекта с включённым приёмом. Открытие такого проекта в
    живой среде начинает слушать порт — знать об этом полезно до запуска.

    Читается только файл рядом с открытым из файла проектом: произвольный путь
    инструмент не принимает, как и остальные инструменты чтения.
    """
    source = session.opened_from()
    if not source:
        raise ToolError(
            "Текущий проект не открывался из файла (создан или ещё не открыт), "
            "поэтому настроек рядом с ним нет.")
    from simintech_api.dbconf import load_db_config
    from simintech_api.exceptions import SimInTechError

    stem = os.path.splitext(source)[0]
    candidates = [stem + ".dblocalconf", stem + ".dbconf"]
    found = [path for path in candidates if os.path.exists(path)]
    if not found:
        return (f"Настроек обмена рядом с проектом нет: искали "
                f"«{os.path.basename(candidates[0])}» и "
                f"«{os.path.basename(candidates[1])}» в каталоге проекта. "
                f"Это обычное состояние — файл появляется, когда настройки "
                f"базы сигналов сохраняли.")
    try:
        config = load_db_config(found[0])
    except SimInTechError as exc:
        raise ToolError(f"файл «{found[0]}» не разобран: {exc}")

    summary = config.as_dict()
    role = summary["role"]
    detail = [f"Файл: {os.path.basename(found[0])}", f"Роль узла: {role}"]
    if role != "не настроен":
        detail.append(f"Синхронизация модельного времени: "
                      f"{'да' if config.sync_time else 'нет'}")
        if config.server_port is not None:
            detail.append(f"Порт приёма данных: {config.server_port}")
        if config.host:
            detail.append(f"Удалённый сервер: {config.host}:{config.port}")
    else:
        detail.append("Сетевой обмен у этого проекта не включён.")
    return "\n".join(detail)


@mcp.tool()
@runtime.com_threaded
def get_project_config() -> str:
    """Показать параметры расчётного слоя проекта.

    Время и шаг расчёта (`starttime`, `endtime`, `hmin`, `hmax`), метод
    интегрирования (`intmet`) и служебные имена слоя — список шире, чем
    «настройки расчёта», и на живом проекте в нём есть, например, `comp_names`.

    Читаются из выгрузки проекта, а не через COM: метода чтения свойств слоя в
    интерфейсе нет, есть только запись. Заодно это список имён, которые в
    проекте есть, — по нему проверяется `set_project_config`.

    У проекта, созданного через `create_project`, параметры есть (он берётся из
    шаблона). Пустой ответ — у проекта без расчётного слоя: тогда расчёт в нём
    не идёт вообще, и это не «настройки по умолчанию», а их отсутствие.
    """
    settings = session.ensure_project().calc_settings()
    if not settings:
        raise ToolError(
            "В проекте нет параметров расчётного слоя: сам слой отсутствует. "
            "Так выглядит проект без шаблона — расчёт в нём не пойдёт.")
    return ("Параметры расчётного слоя:\n"
            + "\n".join(f"  {name} = {value}"
                        for name, value in sorted(settings.items())))


@mcp.tool()
@runtime.com_threaded(mutates_project=True)
def set_project_config(param: str, value: str) -> str:
    """Записать параметр расчётного слоя проекта (`SetLayerProp`).

    Имя сверяется с настройками, которые уже есть в проекте (`get_project_config`).
    Незнакомое отвергается: запись в несуществующее имя среда принимает молча,
    значение не меняется, и отличить это от успеха потом нечем.

    Время расчёта удобнее задавать через `set_calc_time` — он делает то же
    самое для `endtime`.

    Args:
        param: имя параметра (`endtime`, `hmin`, `intmet`, …).
        value: значение строкой — так его принимает среда.
    """
    session.ensure_project().set_calc_setting(param, value)
    return f"{param} = {value}"


#: Состояние файла для проверки записи: метка правки, размер и хеш
#: содержимого (`None` — содержимое прочитать не удалось; файла нет — `None`
#: целиком). Хеш — не избыточность: у файловых систем с грубым разрешением
#: времени (FAT — 2 с, сетевые shares — 1 с) успешная перезапись в ту же
#: секунду не меняет ни метку, ни размер, и вердикт по ним одним ложно
#: отказывал бы в записи, которая состоялась (замечание ревью mcp#26,
#: 01.10.2026); содержимое же меняется — и только его видит хеш.
_FileState = Optional[Tuple[int, int, Optional[str]]]


def _file_state(path: str, *, want_hash: bool = True) -> _FileState:
    """Снять состояние файла (до или после записи); `None` — файла нет.

    Нужно, чтобы отличить «файл появился или обновился» от «старый файл
    остался на месте»: залипшая сессия сообщает об успехе, не записывая
    ничего, и одна лишь проверка «файл есть» приняла бы прежний файл за
    результат записи.

    Метка и хеш снимаются с **одного дескриптора** (`open` + `fstat`), и это
    не педантизм: разнесённые `stat` и чтение могут увидеть два разных
    поколения файла и выдать смешанный снимок за цельный (находка ревью).
    Хеш читается потоком (`file_digest`) — проект бывает в десятки мегабайт,
    а вызов идёт на единственном COM-потоке. `want_hash=False` — когда
    содержимое заведомо не понадобится: зачем второе полное чтение после
    записи, если метка или размер уже разошлись (находка ревью).
    """
    try:
        stat = os.stat(path)
    except OSError:
        return None
    digest: Optional[str] = None
    try:
        with open(path, "rb") as handle:
            # Снимок с одного дескриптора: fstat главнее успевшего устареть
            # `stat`, а хеш читается с того же открытого файла.
            stat = os.fstat(handle.fileno())
            if want_hash:
                digest = hashlib.file_digest(handle, "sha256").hexdigest()
    except OSError:
        # Файл может быть занят на чтение (его как раз пишет среда) — тогда
        # вердикт опирается на метку и размер, как раньше.
        pass
    return (stat.st_mtime_ns, stat.st_size, digest)


def _verify_saved(path: str, before: _FileState) -> None:
    """Проверить, что запись действительно состоялась.

    `SaveProjectXML` в залипшей сессии сообщает об успехе, **не создавая
    файл** (simintech-code#21: симптом повторялся трижды подряд, следом
    `CloseProject` падает с Access violation). Ответ «проект сохранён» по
    такому вызову — ложь, которую клиент обнаружит только на чтении, и
    выдавать её нельзя. Поэтому файл должен появиться (не было раньше) или
    обновиться — меткой правки, размером **или содержимым**.

    Один лишь размер, впрочем, слаб: перезапись другим содержимым той же
    длины его не двигает. Полный набор такой: метка → размер → хеш; вердикт
    «записано» выносится, как только разошёлся любой из них. Содержимое
    после записи читается только при совпавших метке и размере — иначе оно
    ни на что не влияет (находка ревью), а чтение — полное и на COM-потоке.

    Остатки названы честно, их два. Первый: перезапись **идентичным**
    содержимым с той же меткой и размером (одна секунда на грубой ФС) от
    залипания неотличима и отвергается — сообщение говорит «не обновился»,
    а не «среда не записала». Второй: если содержимое **до** записи прочитать
    не удалось (файл занят средой), хеша в снимке нет, и на грубой ФС при
    совпавших метке и размере возможен ложный отказ — отличить нечем.
    Цена обоих остатков — ложный отказ, а не ложный успех: «сохранено» без
    доказательства инструмент не выдаёт.

    Отказ называет обе возможные причины: залипшую сессию и несуществующий
    каталог в пути, — и рецепт от первой: повтор в той же сессии бесполезен,
    помогает перезапуск.
    """
    try:
        stat = os.stat(path)
    except OSError:
        stat = None
    if stat is None:
        after: _FileState = None
    elif before is None or (stat.st_mtime_ns != before[0]
                            or stat.st_size != before[1]):
        # Исход уже решён (файл появился или обновился меткой/размером) —
        # содержимое не читается вовсе.
        after = (stat.st_mtime_ns, stat.st_size, None)
    else:
        after = _file_state(path)
    written = after is not None and (
        before is None
        or after[0] != before[0]
        or after[1] != before[1]
        or (after[2] is not None and before[2] is not None
            and after[2] != before[2]))
    if written:
        return
    if after is None:
        state_text = ("не появился: файла по пути не было и нет"
                      if before is None else
                      "исчез: файл был, а после записи его по пути нет")
    else:
        compared = "метка правки и размер"
        if before is not None and before[2] is not None and after[2] is not None:
            compared += ", и содержимое"
        state_text = f"не обновился (сверены {compared})"
    raise ToolError(
        f"Файл не записан: «{path}» " + state_text
        + ", хотя вызов среды сообщил об успехе. Проверьте, что каталог в "
          "пути существует; если с путём всё в порядке — это признак залипшей "
          "сессии (simintech-code#21): сохранение в ней не проходит, и повтор "
          "бесполезен. Переподключитесь (`disconnect`) и откройте проект "
          "заново — рабочая сессия запись выполнит.")


def _refuse_format_extension_mismatch(path: str, binary: bool) -> None:
    """Отказ, если имя файла обещает не тот формат, которым записываем.

    Среда выбирает формат проекта **по расширению**: `.prt` открывается как
    нативный, `.xprt` — как XML. XML, записанный в файл с именем `.prt`, GUI
    показал «Ошибка загрузки страницы проекта: data error» (живой случай
    02.10.2026: тот же текст, сохранённый как `.xprt`, открылся) — то есть
    промах формата обнаруживается только у пользователя в GUI, а пишущий
    инструмент о нём молчит. Такой файл инструмент создавать не должен;
    отказ называет оба выхода.

    Проверка стоит до всякой работы с проектом: ни формы, ни COM-вызова.

    Имя сверяется после нормализации Win32: хвостовые точки и пробелы
    последнего компонента система отбрасывает сама («m.prt » — это файл
    «m.prt»), поэтому по сырой строке XML прошёл бы в настоящий `.prt` ровно
    через ту же дверь, которую здесь закрываем.
    """
    # CreateFileW сам сокращает хвостовые точки/пробелы последнего компонента
    # («m.prt.», «m.prt » → «m.prt») — сверяемся с именем, которое получится
    # на диске, а не с тем, что пришло строкой.
    lower = path.rstrip(" .").lower()
    if lower.endswith(".prt") and not binary:
        raise ToolError(
            f"«{path}» назван нативным форматом (.prt), а сохраняем XML: среда "
            "открывает проект по расширению и покажет «Ошибка загрузки "
            "страницы проекта: data error» (живой случай 02.10.2026 — тот же "
            "текст под именем .xprt открылся). Сохраните в .xprt или "
            "передайте binary=True.")
    if lower.endswith(".xprt") and binary:
        raise ToolError(
            f"«{path}» назван XML-форматом (.xprt), а сохраняем нативный "
            "бинарный: формат среда выбирает по расширению (тот же замер "
            "02.10.2026 — XML под именем .prt не открылся как нативный), "
            "поэтому содержимое под именем .xprt будет разбираться как XML и "
            "не разберётся. Сохраните в .prt или передайте binary=False.")


@mcp.tool()
@runtime.com_threaded
def save_project(path: str, binary: bool = False,
                 show_form: bool = True) -> str:
    """Сохранить текущий проект в файл.

    Два формата, и назначение у них разное:

    * XML (`.xprt`, по умолчанию) — обычный текст: читается глазами, диффится,
      переживает перенос между версиями;
    * бинарный (`.prt`, `binary=True`) — **нативный формат проекта**, тот самый,
      который открывает GUI SimInTech. XML тоже открывается GUI — под именем
      `.xprt`: формат среда выбирает по расширению, поэтому расхождение имени
      и формата — отказ (см. ниже).

    Перед записью показывается форма проекта (`FormShow`) — иначе файл
    получится «закрытым» для GUI: состояние окна хранится в самом проекте, и
    сессия, работающая через COM, записывает в него признак «окно скрыто». COM
    такой проект потом открывает и считает, а GUI восстанавливает сохранённое
    состояние окна и окна модели не показывает — выглядит как «проект не
    открылся».

    **Запись проверяется по файлу.** Залипшая сессия сообщает об успехе, не
    записывая ничего (simintech-code#21), а «сохранено» без файла — ложь,
    которая всплывёт только на чтении; поэтому файл обязан появиться или
    обновиться — меткой правки, размером или содержимым (у ФС с грубым
    временем одной метки мало), иначе — отказ с диагнозом.

    **Расширение и формат — одно и то же.** Среда выбирает формат проекта по
    расширению (`.prt` — нативный, `.xprt` — XML), поэтому имя, обещающее не
    тот формат, которым пишем, — отказ до всякой работы: XML в `.prt` GUI
    показал бы «data error» (живой случай 02.10.2026). Имя сверяется после
    нормализации Win32: хвостовые точки и пробелы система отбрасывает сама
    (`m.prt ` — это файл `m.prt`).

    **Запись снимает счёт несохранённого.** Ответы мутирующих инструментов
    заканчиваются «Не сохранено: …», а `reload_project` отличает «правки были
    отброшены» от «перечитан тот же файл»; успешная запись — момент, когда
    счёт обнуляется (`session.clear_unsaved`).

    Args:
        path: путь к файлу (абсолютный).
        binary: True — нативный бинарный `.prt`; False — XML `.xprt`.
        show_form: показать форму проекта перед сохранением (см. выше).
            False — для безоконных машин: окно не появится, но и GUI потом
            не покажет окно модели этого проекта.
    """
    _refuse_format_extension_mismatch(path, binary)
    project = session.ensure_project()
    if show_form:
        project.show_form()
        tail = (" Форма проекта показана — без этого файл открывался бы в GUI "
                "без окна модели.")
    else:
        tail = (" Форму не показывали: GUI откроет файл без окна модели.")
    if binary:
        before = _file_state(path)
        project.save_binary(path)
        _verify_saved(path, before)
        session.clear_unsaved()
        return f"Проект сохранён в бинарный файл (.prt): {path}.{tail}"
    before = _file_state(path)
    project.save_xml(path)
    _verify_saved(path, before)
    session.clear_unsaved()
    return f"Проект сохранён в XML (.xprt): {path}.{tail}"


@mcp.tool()
@runtime.com_threaded
def close_project() -> str:
    """Закрыть текущий проект.

    Ответ называет, что именно закрыто, и что текущего проекта больше нет:
    следующий мутирующий вызов после закрытия откажет, и агент не должен
    искать причину (issue #18).

    Участник открытого пакета не закрывается: `CloseProject` исключил бы его
    из состава пакета (живой замер 01.10.2026 — состав 2 → 1), а это операция
    над пакетом, не над проектом. Отказ называет выход: закрыть пакет целиком
    (`close_pack`) или переключиться на другого участника
    (`select_pack_project`).
    """
    project = session.current_project()
    if project is None:
        return "Без изменений: проект не был открыт"
    membership = session.pack_membership()
    if membership is not False:
        if membership is None:
            # Состав пакета не читается — «неизвестно» не разрешение: если
            # проект участник, CloseProject исключит его из состава (замер
            # 01.10.2026), а отличить «участник» от «не участник» нечем.
            raise ToolError(
                "Принадлежность текущего проекта к открытому пакету "
                "проверить не удалось (состав пакета не читается): закрывать "
                "вслепую нельзя — если проект участник, закрытие исключит его "
                "из состава пакета (живой замер 01.10.2026). Повторите "
                "`list_pack_projects`; закрыть пакет целиком можно "
                "`close_pack`.")
        raise ToolError(
            f"Текущий проект — участник открытого пакета "
            f"{session.pack_label()}: его закрытие исключило бы проект из "
            f"состава пакета (живой замер 01.10.2026). Закройте пакет целиком "
            f"(`close_pack`) или выберите другой проект "
            f"(`select_pack_project`).")
    label = session.project_label()
    # Порядок: сначала закрыть, потом сбросить состояние. Если `CloseProject`
    # не ответил, проект остаётся текущим — его видно и можно закрыть повторно,
    # а не потерять открытым внутри mmain.exe.
    project.close()
    session.set_project(None)
    return f"Проект закрыт: {label} — текущего проекта больше нет"
