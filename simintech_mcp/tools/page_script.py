#: Сколько объектов страницы перечислять в отчёте: список — для человека, а не
#: для машинной обработки, поэтому длинный хвост обрезается.
MAX_REPORTED_OBJECTS = 20

#: База имени файла результата контура внутри каталога результатов. Клиенту
#: оно не нужно: строки тела возвращаются в ответе, а каталог — тот же, что у
#: остальных инструментов.
#:
#: Полное имя добавляет уникальный на вызов суффикс (`fresh_name`): общее имя
#: упиралось в запертый файл — обрыв тела оставляет его залоченным процессом
#: SimInTech (`freeobject` не исполнен), и следующий вызов падал на
#: `result_path.unlink` в мосте — WinError 32 (живое наблюдение 02.10.2026,
#: дважды за день). Свежее имя обходит запертый файл; освободится он при
#: выходе mmain.
RESULT_FILE = "page-script-result.txt"


def fresh_name(base: str) -> str:
    """Имя контурного файла, уникальное на вызов: `база-<8 hex>.<расширение>`.

    Запертый прошлым обрывом файл остаётся под своим прежним именем и никому
    не мешает: ни мост, ни чтение по этому имени больше не ходят. Класс отказа
    WinError 32 закрыт обходом, а не борьбой с блокировкой: снять чужой лок
    нельзя, обойти — можно.
    """
    token = uuid.uuid4().hex[:8]
    stem, dot, ext = base.rpartition(".")
    if not dot:
        return f"{base}-{token}"
    return f"{stem}-{token}{dot}{ext}"


def bridge() -> ScriptBridge:
    """Мост для текущего проекта — общая часть всех инструментов модуля."""
    return ScriptBridge(session.ensure_client(), session.ensure_project().id)


def object_names() -> list[str]:
    """Имена объектов текущей страницы — снимки «до» и «после».

    Именно **текущей**: мост ставит скрипт в страницу, которую называет
    `GetCurentPage`, и отчёт обязан считать по той же странице. `list_blocks`
    инструмента берёт главную — для отчёта это было бы расхождение на модели,
    где работа идёт внутри субмодели.
    """
    page = session.ensure_project().get_current_page()
    names: list[str] = []
    for obj in page.get_blocks():
        try:
            names.append(obj.get_name())
        except Exception:                                            # noqa: BLE001
            names.append("(без имени)")
    return names


def change_report(before: list[str], after: list[str],
                  restored: str) -> str:
    """Отчёт об изменениях: было/стало, добавленные имена, возврат скрипта.

    Сравнение идёт по **мультимножествам имён**, а не по числу: среда сама
    переименовывает объекты (`kx_0`), поэтому «стало больше» и «добавлен объект
    X» — разные утверждения, и склеивать их нельзя. Имя, исчезнувшее из снимка,
    добавленным не считается и не показывается: об удалении контур не сообщает
    (удаление БЛОКОВ в этой сборке не предлагается — дефект вендора; линию
    снимает `disconnect_wire` отдельным инструментом и о снятии сообщает сам).
    """
    added = list(after)
    for name in before:
        if name in added:
            added.remove(name)
    shown = ", ".join(added[:MAX_REPORTED_OBJECTS])
    tail = f"; добавлено: {shown}" if shown else "; добавленных объектов нет"
    more = (f" (и ещё {len(added) - MAX_REPORTED_OBJECTS})"
            if len(added) > MAX_REPORTED_OBJECTS else "")
    restored_note = ("Прежний скрипт страницы возвращён: да" if restored
                     else "Прежний скрипт страницы возвращён: нет — он был пуст")
    return (f"Отчёт об изменениях: объектов было {len(before)}, стало "
            f"{len(after)}{tail}{more}. {restored_note}")


@mcp.tool()
@runtime.com_threaded
def get_page_script() -> str:
    """Прочитать скрипт текущей страницы проекта.

    Скрипт живёт в проекте как текст встроенного языка: он исполняется при
    инициализации страницы и на шагах расчёта. Читается он снимком выгрузки
    проекта — COM-метода чтения скрипта не существует (`SetPageScript` пишет и
    о прежнем содержимом не сообщает, `GetPageScript` в интерфейсе нет).

    **Расчёт при чтении не запускается.** Это не деталь: `ProjectStart` — это
    инициализация, и она обнуляет модельное время; инструмент чтения, сдвигающий
    время, уничтожал бы результаты уже сделанного расчёта. Живой замер
    2026-09-29: на остановленном проекте время до и после чтения совпадает.

    Пустой скрипт — не отказ: у проекта из шаблона скрипта страницы нет вовсе, и
    об этом сообщается текстом.
    """
    try:
        script = bridge().read_page_script()
    except ScriptBridgeError as exc:
        raise ToolError(
            f"прочитать скрипт страницы не удалось: {exc}. Чтение опознаёт "
            "страницу по снимку выгрузки проекта, поэтому отказ означает, что "
            "состояние скриптовых записей неопределённо — сверьтесь с копией "
            "проекта, прежде чем что-то в него писать."
        ) from exc
    if not script.strip():
        return ("Скрипт текущей страницы пуст: у этой страницы скрипта нет. "
                "Поставить его можно инструментом `set_page_script`.")
    return f"Скрипт текущей страницы:\n{script}"


def _install_script(script: str) -> None:
    """Оставить скрипт в текущей странице.

    Отдельной функцией — чтобы тест мог подменить её и проверить, что скрипт
    остаётся **только** после успешной проверки компиляции.
    """
    bridge().install_script(script)


def result_path() -> Path:
    """Путь файла результата внутри каталога результатов (песочница).

    Имя уникально на вызов (см. `RESULT_FILE`): запертый прошлым обрывом файл
    результата новому вызову не мешает.
    """
    return Path(os.path.join(sandbox.output_root(), fresh_name(RESULT_FILE)))


def discard_result(path: Path) -> None:
    """Удалить контурный файл результата — best-effort.

    Строки тела приходят ответом (`outcome.lines`), и после прогона файл не
    нужен; без удаления долгая сессия копила бы `page-script-result-*.txt` без
    предела — тот же класс, что закрыт свипом в `check_model_layout` (находка
    ревью PR #54). Обрыв тела оставляет файл запертым (WinError 32, замер
    02.10.2026): снять такой лок нельзя, но и мешать он не может — имя
    уникально на вызов, а освободится файл при выходе `mmain`.
    """
    try:
        path.unlink(missing_ok=True)
    except OSError:                                               # noqa: BLE001
        pass


def run_contour(body: str, *, failed: str) -> Tuple[ContourOutcome, str]:
    """Выполнить тело контуром: `(исход, прежний скрипт)`, либо отказ `ToolError`.

    **Единственная точка рецепта** «мост → `discard_result` → `ToolError` на
    `ScriptBridgeError`» (issue #123). Им живут и инструменты языкового слоя
    (скрипт страницы, субмодель), и блочные (связи, скрипт блока, размер,
    оба фита — через `contour.py` до его слияния сюда), и выгрузка/сборка
    модели со снимком. Копии этого рецепта расходились формулировками: правка
    текста отказа или порядка очистки, попав в одну, не доходила до остальных,
    и инструменты отвечали по-разному на одно состояние среды.

    Отказ моста (`ScriptBridgeError`) означает, что состояние проекта
    неопределённо: тело могло не установиться, а могло и отработать. Поэтому он
    не превращается в исход, а выходит наружу — с объяснением, что проверить.
    Файл результата убирается на любом пути (см. `discard_result`).

    `check_model.py` зовёт мост мимо этого рецепта **намеренно**: его прогон
    кладёт отчёт в файл, который читается после прогона и не удаляется, а
    исход не приговор, а строка отчёта — это отчётный протокол, а не
    тело-правка.
    """
    path = result_path()
    try:
        run = bridge().run_page_script(body, path)
    except ScriptBridgeError as exc:
        discard_result(path)
        raise ToolError(
            f"{failed}: {exc}. Тело идёт в секцию `initialization`, поэтому "
            "расчёт должен сдвинуть модельное время: проверьте, что модель "
            "считает — неподключённый вход останавливает расчёт всей модели "
            "молча."
        ) from exc
    discard_result(path)
    return run.outcome, run.restored_script


def describe_outcome(outcome: ContourOutcome, *, what: str) -> str:
    """Строка состояния для исхода, при котором работа **состоялась**.

    Исходы `not-compiled` и `aborted` сюда не попадают: они означают, что
    работа не сделана, и обрабатываются отказом у вызывающего.
    """
    if outcome.kind == OUTCOME_OK:
        return f"{what}: скрипт собрался и отработал, расчёт идёт."
    if outcome.kind == OUTCOME_MODEL_NOT_RUNNING:
        return (f"{what}: скрипт собрался и отработал, но модель не считает — "
                "вероятная причина: неподключённый вход останавливает расчёт "
                "всей модели.")
    if outcome.kind == OUTCOME_SECTION_NOT_RUN:
        return (f"{what}: секция `initialization` не выполнилась, хотя расчёт "
                "шёл. Причину по этому признаку определить нечем.")
    return f"{what}: исход «{outcome.kind}»."


def refuse_contour_failure(outcome: ContourOutcome, *, failed: str,
                           unsure: Optional[str] = None,
                           aborted_hint: str = "",
                           section_note: str = "") -> None:
    """Отказ по несделанному исходу контура — **единственный маппер** (issue #123).

    «Не сделано» не имеет права вернуться успехом, а последняя строка тела —
    единственный доступный диагноз: ошибки компиляции среда через COM не
    отдаёт. Прежде мапперов было два (`refuse_on_bad_outcome` у языкового слоя
    и `refuse_contour_failure` у блочных инструментов), и они расходились
    формулировками на одном и том же состоянии среды.

    Подлежащие различаются и передаются вызывающим: `failed` («размер не
    записан») — для «не собралось» и «не запускалось»; `unsure` — для обрыва,
    когда «не сделано» утверждать нельзя (тело могло отработать до обрыва);
    не задан — выводится из `failed` («… не выполнена»). `aborted_hint` — что
    проверить после обрыва, `section_note` — уточнение после «тело не
    запускалось» (у `remove_block` оно своё).

    Прелюдии (чистка реестра по перечислению страницы) инструменты делают
    **до** вызова: у `aborted` она своя у каждого. Успешные исходы
    (`ok`/`model-not-running`) маппер пропускает — их описывает
    `describe_outcome`.
    """
    if outcome.kind == OUTCOME_NOT_COMPILED:
        raise ToolError(
            f"{failed}: тело не собралось (текст ошибки — в окне сообщений "
            f"редактора SimInTech; через COM он не читается). Проект не "
            f"изменён.")
    who = unsure if unsure is not None else f"{failed} не выполнена"
    if outcome.kind == OUTCOME_ABORTED:
        detail = (f" Последняя строка тела: {outcome.lines[-1]!r}."
                  if outcome.lines else "")
        hint = f" {aborted_hint}" if aborted_hint else ""
        raise ToolError(
            f"{who}: тело оборвалось на исполнении.{detail}{hint}")
    if outcome.kind == OUTCOME_SECTION_NOT_RUN:
        raise ToolError(
            f"{who}: секция `initialization` не выполнилась — тело не "
            f"запускалось{section_note}. Повторите вызов.")


@mcp.tool()
@runtime.com_threaded(mutates_project=True)
def set_page_script(script: str) -> str:
    """Поставить скрипт в текущую страницу проекта и проверить, что он собрался.

    **Прежний скрипт в ответе.** `SetPageScript` затирает скрипт страницы, не
    сообщая, что там было; инструмент возвращает прежний текст, чтобы клиент мог
    его восстановить. Проверка «собрался ли» — единственная доступная: среда об
    ошибке компиляции молчит, а признак один — расчёт сдвинул модельное время.

    **Как это устроено.** Контурный режим (`run_page_script`) всегда возвращает
    прежний скрипт — иначе он не был бы безопасным. Поэтому работа идёт в два
    шага: сначала скрипт исполняется контуром (проверка компиляции) и прежний
    текст возвращается на место, затем — только если проверка прошла — скрипт
    ставится в страницу насовсем.

    **Чего инструмент не делает.** Не правит скрипт отдельного блока и не
    работает с `.inc`-файлами — это отдельная тема. Не чистит скрипт: пустой
    текст отвергается, потому что `SetPageScript` с пустой строкой стирает
    прежний скрипт молча.

    Args:
        script: текст скрипта встроенного языка для текущей страницы.
    """
    if not script.strip():
        raise ToolError(
            "скрипт пуст. `SetPageScript` с пустой строкой **стирает** прежний "
            "скрипт страницы, поэтому пустой текст отвергается: если цель — "
            "очистить скрипт, сделайте это осознанно и передайте скрипт с одним "
            "комментарием.")
    before = object_names()
    outcome, restored = run_contour(
        script, failed="выполнить скрипт страницы не удалось")
    if outcome.kind in (OUTCOME_NOT_COMPILED, OUTCOME_ABORTED):
        reason = (
            "скрипт не собрался (среда об ошибке молчит; текст ошибки — в окне "
            "сообщений редактора SimInTech)"
            if outcome.kind == OUTCOME_NOT_COMPILED else
            "скрипт оборвался на исполнении; последняя записанная строка: "
            + repr(outcome.lines[-1] if outcome.lines else "")
        )
        raise ToolError(
            f"скрипт не поставлен: {reason}. Прежний скрипт страницы возвращён "
            "на место, проект не изменён.")
    _install_script(script)
    after = object_names()
    return (
        f"Скрипт поставлен в текущую страницу.\n"
        f"{describe_outcome(outcome, what='Вердикт')}\n"
        f"{change_report(before, after, restored)}\n"
        f"Чтобы вернуть прежний скрипт — передайте его текст в "
        f"`set_page_script`.\n"
        f"---- прежний скрипт ----\n{restored}"
    )


@mcp.tool()
@runtime.com_threaded(mutates_project=True)
def run_page_script(script: str) -> str:
    """Выполнить произвольный скрипт в секции `initialization` текущей страницы.

    Это **клапан**: тело исполняется в секции `initialization` — единственном
    месте, где разрешено создавать объекты (`createmodel`, `createprimitiv`), —
    и по маркерам контура различается пять исходов. Прежний скрипт страницы
    возвращается на место всегда, изменения модели живут в памяти до
    `save_project`.

    **Исходы и что они значат.** `ok` — тело дошло до конца, расчёт идёт;
    `model-not-running` — скрипт собрался и отработал, а модель не считает
    (вероятная причина — неподключённый вход); `aborted` — обрыв на исполнении,
    в ответе последняя записанная строка; `not-compiled` — скрипт не собрался
    (текст ошибки — в окне сообщений редактора SimInTech, через COM он не
    читается); `section-not-run` — секция не выполнилась, причина по этому
    признаку не определяется.

    **Тело пишет результат само**; написанные строки возвращаются в ответе.
    Пишутся они в уже открытый контуром дескриптор `fid`
    (`writelnutf8(fid, "…")`): открывать файл, объявлять дескриптор и
    закрывать его не нужно, а сам файл лежит в каталоге результатов. Если
    тело зовёт чужой код, присваивающий `fid` (вендорская процедура
    `export_1layer_topology` делает именно это), после такого вызова пишите
    процедурой `br_writeln("…")`: она находит дескриптор контура сама, тогда
    как `fid` после чужого кода указывает на чужой (возможно, уже
    освобождённый) файл и запись через него обрывает тело.

    **Осторожно:** это исполнение произвольного кода встроенного языка в
    процессе SimInTech — тело может читать и писать файлы, менять проект и
    запускать расчёт. Инструмент ограничивает только то, что делает сам: путь
    результата — в каталоге результатов, число шагов расчёта задано таймаутом
    роста модельного времени.

    **Чего инструмент не делает.** Не удаляет БЛОКИ: `removeprimitiv` роняет
    старт расчёта access violation'ом, когда создание и удаление идут в
    ОДНОМ прогоне (замеры 04.10.2026 и 06.10.2026); удаление блоков —
    отдельным прогоном, инструмент `remove_block` (линию снимает
    `disconnect_wire`). Серия `removeprimitiv` по id (например, снятие линий
    циклом в одном прогоне) может «ослепить» топологию портов до
    сохранения и переоткрытия проекта — проверяйте порты на свежем
    экземпляре (подробности в `disconnect_wire`).

    Args:
        script: тело на встроенном языке; секции `initialization` и `end;`
            дописывает инструмент — объявлять их в теле не нужно.
    """
    before = object_names()
    outcome, restored = run_contour(
        script, failed="выполнить скрипт страницы не удалось")
    after = object_names()
    lines = "\n".join(outcome.lines)
    return (
        f"Исход: {outcome.kind}\n"
        f"{describe_outcome(outcome, what='Что видно')}\n"
        f"{change_report(before, after, restored)}\n"
        f"---- строки тела ----\n{lines}"
    )


#: База имени файла сбора внутри каталога результатов. Клиенту оно не нужно:
#: данные возвращаются в ответе, а каталог — тот же, что у остальных
#: инструментов.
#:
#: Полное имя, как и у `RESULT_FILE`, уникально на вызов: прежний файл сбора
#: может быть залочен ещё пишущей субмоделью (тот же класс WinError 32), а
#: заодно сборы разных вызовов не затирают друг друга — прежний остаётся
#: читаемым по названному в ответе пути.
COLLECT_FILE = "submodel-collect.txt"

#: Предел данных сбора, отдаваемых в ответ: строки читает человек.
MAX_COLLECT_BYTES = 64 * 1024


def _collect_body(body: str, collect_path: str) -> str:
    """Обернуть строки сбора в рецепт дозаписи файла.

    Рецепт измерен 2026-09-29 (пробы collect1–collect5, поставка 2.26.6.23):

    * присвоенный скрипт исполняется **на каждом шаге** расчёта, и переменные
      между шагами переживают (счётчик в пробе вырос до 37);
    * файл, открытый в `initialization`, к моменту тела уже не тот: писать
      через него нельзя, а сам он держит блокировку — файл сбора остаётся
      залоченным процессом SimInTech, и снаружи его не прочитать;
    * поэтому файл открывается **и закрывается телом на каждом шаге**, а
      дописывание идёт `seek` в конец — режимы создания (`-1`) и записи (`1`)
      усекают файл, и в нём оставалась бы одна последняя строка;
    * `filesize` принимает **дескриптор**, а не имя файла (на этом упала третья
      проба: `filesize("путь")` обрывает тело молча).

    Файл создаёт вызывающий: режим `2` («чтение и запись») новый файл не создаёт.
    """
    literal = collect_path.replace("\\", "/").replace('"', "")
    lines = [line for line in body.splitlines() if line.strip()]
    rendered = "\n".join(lines)
    return (
        f'fw = createfile("{literal}", 2);\n'
        "seek(fw, filesize(fw));\n"
        f"{rendered}\n"
        "freeobject(fw);\n"
    )


@mcp.tool()
@runtime.com_threaded(mutates_project=True)
def inject_submodel_script(script: str) -> str:
    """Создать субмодель со скриптом сбора данных и вернуть собранное.

    Субмодель создаётся пустой (`createprimitiv` с кодом типа 102), ей
    присваивается скрипт, и вызывается `reinitsubmodel` — **без него скрипт не
    компилируется**, и снаружи это выглядит как «присвоили — и ничего не
    происходит», без единого сообщения (замер 2026-09-29). Присвоенный скрипт
    исполняется на каждом шаге расчёта.

    **Как писать тело.** `script` — строки, исполняемые на каждом шаге; файл
    сбора уже открыт и в конце него выставлена позиция — пишите через дескриптор
    `fw`: `writelnutf8(fw, "шаг");`. Объявлять `fw` не нужно, закрывать тоже.
    Строки сбора **дописываются**: в ответе будет по строке на каждый шаг.

    **Что в ответе.** Вердикт контура, отчёт об изменениях (в нём видно
    созданную субмодель) и собранные данные — содержимое файла сбора, не больше
    64 КиБ. Пустой файл — **отказ**: он означает, что присвоенный скрипт не
    исполнялся.

    **Субмодель остаётся в проекте и пишет дальше.** Контур делает столько
    шагов, сколько нужно, чтобы подтвердить рост модельного времени, — этого
    мало для длинного сбора. Инжектированная субмодель продолжает писать на
    **каждом** шаге расчёта: выполните `run`/`step` (или дайте расчёт дольше),
    и файл сбора вырастет — прочитать его можно `read_output_file`, путь назван
    в ответе (замер 2026-09-29: после инжектирования файл вырос до 5459 строк,
    пока шёл расчёт). У каждого вызова свой файл сбора: имя уникально, поэтому
    повторный вызов прошлый сбор не затирает. Учтите: если модель не считает
    (неподключённый вход), время стоит, а `run(to_time=…)` будет ждать его
    роста и упрётся в таймаут — тогда как шаги и запись данных при этом идут.

    **Чего инструмент не делает.** Не соединяет субмодель с моделью и не
    добавляет в неё порты. `time` внутри присвоенного скрипта как число не
    читается (`floattostr(time)` даёт пустую строку, замер 2026-09-29), поэтому
    счётчик шагов ведётся телом клиента, а не временем.

    Args:
        script: строки сбора, исполняемые на каждом шаге расчёта; пишут через
            дескриптор `fw`.
    """
    if not script.strip():
        raise ToolError(
            "тело сбора пусто: скрипту нечего записывать, и файл сбора остался "
            "бы пустым — то есть отказ пришёл бы всё равно, но позже и с менее "
            "понятной причиной.")
    collect_path = os.path.join(sandbox.output_root(), fresh_name(COLLECT_FILE))
    # Файл создаём заранее и пустым: скрипт открывает его режимом «чтение и
    # запись», а этот режим новый файл не создаёт. Чистка прошлого прогона
    # больше не нужна: имя уникально, и этот пустой файл всегда наш.
    Path(collect_path).write_text("", encoding="utf-8")
    before = object_names()
    outcome, restored = run_contour(
        build_inject_submodel_script_body(_collect_body(script, collect_path)),
        failed="создать субмодель со скриптом не удалось")
    after = object_names()
    if outcome.kind in (OUTCOME_NOT_COMPILED, OUTCOME_ABORTED):
        raise ToolError(
            f"субмодель со скриптом не создана: исход «{outcome.kind}»"
            + (f", последняя строка тела: {outcome.lines[-1]!r}"
               if outcome.lines else "")
            + ". Прежний скрипт страницы возвращён, проект не изменён.")
    data, truncated, error = sandbox.load_result_file(
        collect_path, MAX_COLLECT_BYTES, sandbox.MISSING_RESULT_FILE)
    if error:
        raise ToolError(
            f"субмодель создана, но файла сбора нет: {error}. Данные пишет "
            "присвоенный скрипт — он исполняется на каждом шаге расчёта, "
            "поэтому пустой ответ означает, что расчёт не шёл.")
    collected = data.decode("utf-8", errors="replace")
    if not collected.strip():
        raise ToolError(
            "субмодель создана, но файл сбора пуст: присвоенный скрипт не "
            "исполнялся. Так выглядит пропущенный `reinitsubmodel` — поэтому "
            "инструмент добавляет его сам; проверьте, что модель считает "
            "(неподключённый вход останавливает расчёт молча).")
    note = "\n… данные обрезаны по пределу" if truncated else ""
    return (
        f"Субмодель со скриптом сбора создана.\n"
        f"{describe_outcome(outcome, what='Вердикт')}\n"
        f"{change_report(before, after, restored)}\n"
        f"---- собранные данные ({collect_path}) ----\n{collected}{note}"
    )


def activate_or_refuse(page: Any, *, action: str,
                       where: Optional[str] = None) -> None:
    """Сделать страницу правки текущей или отказать — до контура.

    Скрипт ставится в текущую страницу (`SetPageScript` → `GetCurentPage`),
    и адресация по id ищется на ней: без активации запись ушла бы мимо блока
    или в блок-двойник с тем же id (находка ревью PR #94). Не удалось
    активировать — **отказ**, а не запись вслепую: промах выглядел бы как
    «среда не приняла запись» и уводил бы диагноз в сторону среды.

    Блок повторялся у трёх инструментов (ветвь, размер, габариты фитов) с
    дословным обоснованием и разными текстами — тексты сведены сюда
    (находка ревью PR #122): `action` называет действие («ветвь не
    создана»), `where` — страницу, когда её имя известно (у фитов).
    Переехала из `contour.py` вместе с контурным ядром (issue #123): это
    страничная механика, и её место — рядом с ядром.
    """
    try:
        page.activate()
    except Exception as exc:                                  # noqa: BLE001
        named = f" «{where}»" if where else ""
        raise ToolError(
            f"{action}: страницу{named} не удалось сделать активной "
            f"({type(exc).__name__}: {exc}) — запись по id могла бы уйти в "
            f"блок другой страницы. Проект не изменён.") from exc


def return_main_active(main: Any, lines: List[str]) -> None:
    """Вернуть главную страницу активной, назвав провал возврата.

    Обход фитов активирует каждую страницу, а следующая контурная операция
    (выгрузка, снимок) снимает ИМЕННО активную (живой случай 06.10.2026).
    Молчаливый `pass` здесь оставлял бы субмодель текущей и инструмент
    отчитывался бы успехом (находка ревью PR #122): не получилось вернуть —
    это примечание, а не отказ (правка-то сделана), но и не тишина.
    """
    try:
        main.activate()
    except Exception as exc:                                  # noqa: BLE001
        lines.append(f"главную не удалось вернуть активной "
                     f"({type(exc).__name__}: {exc}) — следующая контурная "
                     f"операция снимет ТЕКУЩУЮ страницу, а не главную.")
