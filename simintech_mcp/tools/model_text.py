#: База имени файла выгрузки внутри каталога результатов. Клиенту она не
#: нужна: путь возвращается в ответе, а каталог — тот же, что у остальных
#: инструментов. Полное имя уникально на вызов (`page_script.fresh_name`):
#: прошлый запертый обрывом файл не мешает, а прошлые артефакты не затираются.
MODEL_TEXT_FILE = "model-text.txt"

#: Тела обеих операций исполняет контурное ядро `page_script.run_contour`:
#: рецепт «мост → `discard_result` → `ToolError` на `ScriptBridgeError`» у
#: выгрузки, сборки и снимка — общий (issue #123). Здешние копии
#: (`bridge`, `run_contour`, `result_path`) удалены при слиянии ядра.


def page_export_text() -> "Tuple[str, bool, ContourOutcome, Path]":
    """Текст выгрузки страницы: (текст, обрезано, исход, путь файла).

    Без обёртки инструмента и COM-потока: тем же путём идёт `layout_place`,
    когда реестр `connect` пуст (проект открыт из файла) — раскладке нужен граф
    страницы, а COM концов линий не отдаёт, их отдаёт только выгрузка.
    """
    root = sandbox.output_root()
    text_path = os.path.join(root, fresh_name(MODEL_TEXT_FILE))
    outcome, _restored = run_contour(
        build_export_model_text_body(text_path),
        failed="выгрузка текста модели не удалась")
    refuse_contour_failure(outcome, failed="выгрузка текста модели")

    data, truncated, error = sandbox.load_result_file(
        text_path, sandbox.MAX_OUTPUT_BYTES, sandbox.MISSING_RESULT_FILE
    )
    if error:
        raise ToolError(
            f"скрипт выгрузки отработал, но файла нет: {error}. Выгрузка идёт "
            "в каталог результатов, и туда же указывает путь в скрипте."
        )
    text = data.decode("utf-8", errors="replace").removeprefix("\ufeff")
    return text, truncated, outcome, Path(text_path)


def _wire_value(line: str) -> str:
    """Значение адреса `src`/`dst` из строки выгрузки (без кавычек)."""
    return line.split("=", 1)[1].strip().strip('",')


def _block_of(address: str) -> str:
    """Имя блока или провода из адреса: часть до первого двоеточия."""
    return address.split(":")[0]


def parse_page_wires(text: str) -> "List[Tuple[str, str, str]]":
    """Записи проводов страницы: (имя провода, адрес источника, адрес конца).

    Адрес — как в выгрузке: у прямого провода `block:out:N` / `block:in:N`
    (N — индекс порта), у ветви на месте источника стоит имя провода
    (`src = "wireName:K"`): ветвь — не новый источник, а точка съёма с той же
    линии (K — номер точки с нуля; замеры 2026-09-28/29). Разбор не решает,
    что с записью делать: раскладке (`parse_page_graph`) нужен граф с
    разрешением ветвей, выравниванию (`parse_page_pairs`) — только прямые
    пары с индексами портов.
    """
    wires: "List[Tuple[str, str, str]]" = []
    name = ""
    src = ""
    for raw in text.replace("\r\n", "\n").split("\n"):
        line = raw.strip()
        if line.endswith(": (") and not line.startswith("type"):
            name, src = line[:-3], ""
            continue
        if not name:
            continue
        if line.startswith("src = "):
            src = _wire_value(line)
            continue
        if line.startswith("dst = ") and src:
            wires.append((name, src, _wire_value(line)))
            src = ""
    return wires


def graph_from_wires(
        wires: "List[Tuple[str, str, str]]") -> "List[Tuple[str, str]]":
    """Рёбра страницы из записей проводов — с разрешением ветвей.

    Ветвь — не новый источник, а точка съёма с той же линии, поэтому её
    источник разрешается по исходному проводу. Без этого раскладчик не видит
    ветви боевой модели и кладёт каналы на 8 px уже канона за каждую.

    Отделена от `parse_page_graph` ради `layout_place`: там из одной выгрузки
    нужны и граф, и прямые пары, и двойной разбор целого текста (`parse_page_
    wires` дважды) был бы лишним — на больших страницах это заметно
    (находка ревью PR #91).
    """
    sources: "Dict[str, str]" = {
        name: _block_of(src) for name, src, _dst in wires}

    def resolve(value: str) -> str:
        for _step in range(8):
            if value not in sources:
                break
            value = sources[value]
        return value

    return [(resolve(_block_of(src)), _block_of(dst))
            for _name, src, dst in wires]


def parse_page_graph(text: str) -> "List[Tuple[str, str]]":
    """Рёбра страницы из выгрузки — с разрешением ветвей (см. граф)."""
    return graph_from_wires(parse_page_wires(text))


def pairs_from_wires(
        wires: "List[Tuple[str, str, str]]") -> "List[Tuple[str, int, str, int]]":
    """Прямые пары с индексами портов: (источник, out, приёмник, in).

    Только провода, у которых источник — блок (`src = "block:out:N"`). Ветвь
    (`src = "wireName:K"`) пропускается: K — точка съёма с линии, а не порт
    источника, и выравнивание по ней поставило бы выход источника под
    случайную точку маршрута. Индексы N — те же, что у COM-адресации портов:
    живой замер 06.10.2026 — у провода с `dst = "LangBlock_0:in:0"` конец
    сошёлся по координате с первым входом блока. Незнакомый формат адреса
    пропускается, а не угадывается: пара с выдуманным индексом сдвинула бы
    блок по ложной цели.
    """
    pairs: "List[Tuple[str, int, str, int]]" = []
    for _name, src, dst in wires:
        src_block, out_sep, out_index = src.partition(":out:")
        dst_block, in_sep, in_index = dst.partition(":in:")
        if not out_sep or not in_sep:
            continue
        if not (out_index.isdigit() and in_index.isdigit()):
            continue
        pairs.append((src_block, int(out_index), dst_block, int(in_index)))
    return pairs


def parse_page_pairs(text: str) -> "List[Tuple[str, int, str, int]]":
    """Прямые пары из выгрузки (см. пары из записей проводов)."""
    return pairs_from_wires(parse_page_wires(text))


@mcp.tool()
@runtime.com_threaded
def export_model_text() -> str:
    """Выгрузить модель текущей страницы проекта в декларативный текст.

    Так читается то, чего COM не отдаёт: концы линий (какие блоки соединены),
    адреса ветвей, вложенные страницы субмоделей целиком и скрипт самой
    страницы. Для сборки модели из текста обратно служит `import_model_text`.

    **Порядок работы.** Инструмент ставит тело контура в текущую страницу
    (прежний скрипт возвращается на место), запускает расчёт на несколько шагов
    и читает файл выгрузки из каталога результатов. Модельное время при этом
    сдвинется (как после `step`) — если модель считает. На несчитающей модели
    выгрузка **всё равно удаётся**: `savemodeltofile` пишется из секции
    `initialization`, поэтому текст приходит полным, а ответ начинается со
    строки состояния — «модель не считает» (живое наблюдение 01.10.2026:
    субмодель со стоящим расчётом выгрузилась целиком). Отказ здесь — только
    когда тело не отработало вовсе (`not-compiled`, `aborted`).

    **Что в ответе.** Текст выгрузки: свойства страницы (`x_center`), объекты
    записями вида `Имя: (type = "Класс", points = […], свойства)`, провода
    (`type = "wire"`, `src`, `dst`) и вложенные `subsystem:`. Объём ограничен,
    как и у `read_output_file`: при превышении текст обрезается с пометкой.
    Поле `script` страницы содержит временный скрипт контура — не скрипт проекта
    (прежний возвращается на место после прогона).
    """
    text, truncated, outcome, text_path = page_export_text()
    note = (
        f"\n… текст обрезан по пределу {sandbox.MAX_OUTPUT_BYTES} байт"
        if truncated
        else ""
    )
    # Состояние — ДО текста: он бывает в сотни строк, и предупреждение не
    # должно тонуть в его конце. Стоящий расчёт выгрузке не мешает (файл
    # пишется из `initialization`), но агент решает по ответу, что делать
    # дальше, и обязан видеть, что модель не считает.
    head = ""
    if outcome.kind == OUTCOME_MODEL_NOT_RUNNING:
        head = (describe_outcome(outcome, what="Выгрузка")
                + " Текст при этом полный: savemodeltofile пишется из секции "
                  "`initialization`, а не из шагов расчёта.\n")
    return f"{head}Текст модели (файл {text_path}):\n{text}{note}"


def _wire_count() -> Optional[int]:
    """Число линий текущей страницы или `None`, если перечислить не удалось."""
    try:
        return len(session.ensure_project().get_current_page().get_wires())
    except Exception:                                          # noqa: BLE001
        return None


def _trace_note(before: Optional[int], after: Optional[int]) -> str:
    """Напоминание о трассировке: импорт линии не прокладывает.

    Провода приходят геометрией из текста (часто все точки в (0,0)) и не
    трассированы; прокладывает их `layout_place` — он же и расставляет
    блоки. Подсказка обязана быть в ответе: в кейсе #24 сразу после импорта
    модель выглядела нечитаемой, и клиент шёл разбираться с диагоналями
    вместо одного вызова.

    Считается **прирост** линий (чтения до и после контура), а не общее
    число: прежде по одному счётчику ответ утверждал «после импорта они не
    трассированы» про все линии страницы, включая уже проложенные чужие
    (находка ревью 02.10.2026). Ошибка чтения не превращается в отказ: модель
    уже импортирована, и отказ после изменения состояния выглядел бы как
    «импорт не удался».
    """
    if before is None or after is None:
        return ("ВНИМАНИЕ: перечислить линии страницы не удалось — "
                "ортогональность проверьте в GUI.")
    added = after - before
    if after == 0:
        return "Линий связи на странице нет — трассировать нечего."
    if added <= 0:
        return (f"Линии связи: {after}; новых импорт не добавил — "
                f"существующие линии не затронуты.")
    return (f"Линии связи: +{added} (всего {after}). Геометрия добавленных "
            f"не пересчитана — участки могут быть неортогональными; "
            f"`layout_place` без аргументов расставит блоки и проложит линии.")


def _duplicate_record_names(model_text: str) -> List[Tuple[str, int]]:
    """Имена записей текста, встречающиеся больше одного раза: (имя, число).

    Записи модели — поля record-литерала (`Имя: ( … )`). Среда **не
    компилирует повтор имени записи**: текст с двумя `Wire:` отвергается
    целиком (живой замер 08.10.2026 — исход not-compiled, ни один объект не
    создан), и ошибка видна только в окне редактора SimInTech. При этом дубли
    порождает и сама среда: `export_model_text` печатает ветви под одним
    автоименем (`MBTYWire` ×N), так что круг «выгрузка → импорт» спотыкается
    об это штатно.

    Повтор имени в **разных** субмоделях этим сканом тоже считается — потому
    находка идёт «первой причиной к проверке» при not-compiled, а не
    приговором: текст — не наш формат, и полный разбор его грамматики
    сознательно не делается (см. докстринг инструмента). Замер 08.10.2026:
    две субмодели, в каждой запись `pin1`, — импорт **прошёл**; повтор в
    одной записи (два `Wire` на верхнем уровне) — not-compiled.
    """
    counts: Dict[str, int] = {}
    for line in model_text.splitlines():
        match = re.match(r"\s*([A-Za-z_][\w]*)\s*:\s*\(", line)
        if match:
            name = match.group(1)
            counts[name] = counts.get(name, 0) + 1
    return sorted(((name, count) for name, count in counts.items() if count > 1),
                  key=lambda item: (-item[1], item[0]))


@mcp.tool()
@runtime.com_threaded(mutates_project=True)
def import_model_text(model_text: str) -> str:
    """Собрать объекты модели из декларативного текста.

    Текст — того же формата, что возвращает `export_model_text`: записи
    `Имя: (type = "Класс", points = […], свойства)` и провода (`type = "wire"`
    с `src`/`dst`). Объекты добавляются в текущий контейнер; **старые не
    трогаются** — `createmodel` дополняет модель (вендор подтвердил
    2026-09-28): их координаты и ручная раскладка переживают повторные
    импорты (контракт #24 п.6, наблюдение 01.10.2026 — правки после ручной
    доводки её не сдвинули).

    **Текст — это код, а не данные.** Форма `const model : ( … );` — часть
    встроенного языка, и текст принимает компилятор SimInTech, а не сервер:
    инструмент не разбирает его грамматику и не проверяет по списку разрешённого.
    Так сделано намеренно: свой парсер языка неизбежно был бы неполным, а
    неполный разбор молча ломал бы корректные модели — ровно тот класс отказа,
    против которого весь остальной контур (среда об ошибках скрипта молчит).
    Поэтому текст берут из `export_model_text` своего же проекта или собирают по
    образцу, а не из чужого источника.

    **Выгрузку можно подавать как есть.** Текст, который вернул
    `export_model_text` (вместе с обрамляющими скобками, свойствами страницы и
    полем `script`), принимается без правки: замер 2026-09-29 — объекты
    создаются, вердикт `ok`. Прежде это не работало по нашей вине: выгрузка
    оборачивалась в `const model : ( … )` **второй раз**, и среда молча не
    компилировала скрипт (двойная вложенность скобок).

    **Кавычки.** Внутри текста кавычка задаётся `chr(34)`: удвоение `""` в этой
    сборке даёт пустую строку, а обратный слэш не экранирует. Текст с удвоенными
    кавычками при этом выглядит правдоподобно, объектов не создаёт и сообщений
    не оставляет — заметить это можно только по отчёту об изменениях.

    **Границы `createmodel` (живые замеры 03.10.2026).** Текст собирают строго
    по форме выгрузки — три вещи ломаются молча или со сбивающим сообщением:

    - **Трейлинг-запятая после последнего свойства — `not-compiled`.** `points
      = […],` перед `)` даёт «Символ , не может быть использован в выражении»,
      причём указатель — на строку `createmodel(…)` в обёртке. Канон: последнее
      свойство — без запятой (как в выгрузке).
    - **Ветвление от выхода текстом не воспроизводится.** Второй провод из того
      же выхода «пришивается» цепочкой: в выгрузке он становится
      `src = "tw1:0"` — ссылкой на провод. Провода к одному входу (разные
      источники) работают. Поэтому импорт — «один провод на выход», а ветвления
      стройте `connect` (он делает их правильно). Это же ограничение —
      у round-trip: выгрузку с ветвлением повторный импорт воспроизведёт
      цепочкой, а не ветвлением.
    - **Провода к блокам из того же текста портятся** — адреса ещё не
      разрешены. Рабочий порядок: блоки → (при необходимости `save_project` и
      переоткрытие) → провода.

    **Добавленные линии не трассированы.** Провода приходят геометрией из
    текста (часто все точки в (0,0)); если импорт добавил линии, ответ
    напоминает вызвать `layout_place` без аргументов — он расставит блоки и
    проложит линии ортогонально (в кейсе #24 схема сразу после импорта
    выглядела нечитаемой). Прироста нет — ответ скажет и это, а не припишет
    импорту чужие линии.

    **Пины блоков «Язык программирования» импорт не пересобирает.**
    `createmodel` их не генерирует (замер 01.10.2026: у свежего PL-блока один
    дефолтный вход, а провода к остальным пинам создаются половинками молча),
    а автоматический обход с `reinitlangblock` **сознательно не делается**:
    пересборка пинов измеренно неполна для объявлений с размером
    (`a[3]: array` даёт два входа вместо трёх, замер 02.10.2026), и цикл
    затронул бы уже настроенные блоки. Если после импорта у PL-блока нужны
    пины — доведите его осознанно: `set_block_script` (перезапись скрипта тем
    же текстом = «setprop + reinitlangblock») или `reinitlangblock` в
    `run_page_script`; провода-половинки досоединяет `connect` штатно.
    Имена объектов из текста креатемодел приводит к **нижнему регистру**
    (`Trigger` → `trigger`, замер 03.10.2026), а `connect` **регистрозависим**
    («блок не найден» на исходное имя) — адресуйте блоки по фактическим именам
    из ответа импорта или `list_blocks`.

    **Порядок работы** как у выгрузки: тело идёт в секцию `initialization`,
    расчёт делает несколько шагов, прежний скрипт страницы возвращается на
    место, изменения модели живут в памяти до `save_project`.

    Args:
        model_text: декларативный текст модели (как из `export_model_text`).
    """
    if not model_text.strip():
        raise ToolError(
            "текст модели пуст: собирать нечего. Пустой текст — не «ничего не "
            "сделает»: он означает, что на стороне клиента содержимое потеряно, "
            "и молчание здесь скрыло бы это.")
    dups = _duplicate_record_names(model_text)
    wires_before = _wire_count()
    before = object_names()
    outcome, restored = run_contour(
        build_import_model_text_body(model_text),
        failed="собрать модель из текста не удалось")
    try:
        refuse_contour_failure(
            outcome, failed="сборка модели",
            aborted_hint=("Часть объектов могла создаться до обрыва — "
                          "сверьте `list_blocks`/`list_wires`; прежний "
                          "скрипт страницы возвращён."))
    except ToolError as exc:
        # Диагноз not-compiled — самый дорогой: текст ошибки виден только в
        # окне редактора SimInTech. Повтор имени записи — единственная
        # причина, которую можно назвать по тексту, и частая на круге
        # «выгрузка → импорт» (среда печатает ветви одним автоименем).
        if outcome.kind == OUTCOME_NOT_COMPILED and dups:
            names = ", ".join(f"`{name}` ({count}×)" for name, count in dups[:3])
            more = f" и ещё {len(dups) - 3}" if len(dups) > 3 else ""
            raise ToolError(
                f"{exc} Возможная причина названа: в тексте повторяются "
                f"имена записей — {names}{more}. Повтор имени записи среда "
                f"не компилирует (первая причина к проверке при "
                f"not-compiled); уникализируйте имена, поправив и ссылки "
                f"`src=\"<имя>:0\"` — за образец возьмите выгрузку свежего "
                f"проекта."
            ) from exc
        raise
    after = object_names()
    wires_after = _wire_count()
    return (
        f"Модель собрана из текста.\n"
        f"{describe_outcome(outcome, what='Вердикт')}\n"
        f"{change_report(before, after, restored)}\n"
        f"{_trace_note(wires_before, wires_after)}"
    )
