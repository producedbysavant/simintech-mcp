#: База имени файла выгрузки внутри каталога результатов. Клиенту она не
#: нужна: путь возвращается в ответе, а каталог — тот же, что у остальных
#: инструментов. Полное имя уникально на вызов (`page_script.fresh_name`):
#: прошлый запертый обрывом файл не мешает, а прошлые артефакты не затираются.
MODEL_TEXT_FILE = "model-text.txt"

#: Тела обеих операций исполняет контурное ядро `page_script.run_contour`:
#: рецепт «мост → `discard_result` → `ToolError` на `ScriptBridgeError`» у
#: выгрузки, сборки и снимка — общий (issue #123). Здешние копии
#: (`bridge`, `run_contour`, `result_path`) удалены при слиянии ядра.


def page_export_text() -> "Tuple[str, bool, ContourOutcome, Path]":
    """Текст выгрузки страницы: (текст, обрезано, исход, путь файла).

    Без обёртки инструмента и COM-потока: тем же путём идёт `layout_place`,
    когда реестр `connect` пуст (проект открыт из файла) — раскладке нужен граф
    страницы, а COM концов линий не отдаёт, их отдаёт только выгрузка.
    """
    root = sandbox.output_root()
    text_path = os.path.join(root, fresh_name(MODEL_TEXT_FILE))
    outcome, _restored = run_contour(
        build_export_model_text_body(text_path),
        failed="выгрузка текста модели не удалась")
    refuse_contour_failure(outcome, failed="выгрузка текста модели")

    data, truncated, error = sandbox.load_result_file(
        text_path, sandbox.MAX_OUTPUT_BYTES, sandbox.MISSING_RESULT_FILE
    )
    if error:
        raise ToolError(
            f"скрипт выгрузки отработал, но файла нет: {error}. Выгрузка идёт "
            "в каталог результатов, и туда же указывает путь в скрипте."
        )
    text = data.decode("utf-8", errors="replace").removeprefix("\ufeff")
    return text, truncated, outcome, Path(text_path)


def _wire_value(line: str) -> str:
    """Значение адреса `src`/`dst` из строки выгрузки (без кавычек)."""
    return line.split("=", 1)[1].strip().strip('",')


def _block_of(address: str) -> str:
    """Имя блока или провода из адреса: часть до первого двоеточия."""
    return address.split(":")[0]


def parse_page_wires(text: str) -> "List[Tuple[str, str, str]]":
    """Записи проводов страницы: (имя провода, адрес источника, адрес конца).

    Адрес — как в выгрузке: у прямого провода `block:out:N` / `block:in:N`
    (N — индекс порта), у ветви на месте источника стоит имя провода
    (`src = "wireName:K"`): ветвь — не новый источник, а точка съёма с той же
    линии (K — номер точки с нуля; замеры 2026-09-28/29). Разбор не решает,
    что с записью делать: раскладке (`parse_page_graph`) нужен граф с
    разрешением ветвей, выравниванию (`parse_page_pairs`) — только прямые
    пары с индексами портов.
    """
    wires: "List[Tuple[str, str, str]]" = []
    name = ""
    src = ""
    for raw in text.replace("\r\n", "\n").split("\n"):
        line = raw.strip()
        if line.endswith(": (") and not line.startswith("type"):
            name, src = line[:-3], ""
            continue
        if not name:
            continue
        if line.startswith("src = "):
            src = _wire_value(line)
            continue
        if line.startswith("dst = ") and src:
            wires.append((name, src, _wire_value(line)))
            src = ""
    return wires


def graph_from_wires(
        wires: "List[Tuple[str, str, str]]") -> "List[Tuple[str, str]]":
    """Рёбра страницы из записей проводов — с разрешением ветвей.

    Ветвь — не новый источник, а точка съёма с той же линии, поэтому её
    источник разрешается по исходному проводу. Без этого раскладчик не видит
    ветви боевой модели и кладёт каналы на 8 px уже канона за каждую.

    Отделена от `parse_page_graph` ради `layout_place`: там из одной выгрузки
    нужны и граф, и прямые пары, и двойной разбор целого текста (`parse_page_
    wires` дважды) был бы лишним — на больших страницах это заметно
    (находка ревью PR #91).
    """
    sources: "Dict[str, str]" = {
        name: _block_of(src) for name, src, _dst in wires}

    def resolve(value: str) -> str:
        for _step in range(8):
            if value not in sources:
                break
            value = sources[value]
        return value

    return [(resolve(_block_of(src)), _block_of(dst))
            for _name, src, dst in wires]


def parse_page_graph(text: str) -> "List[Tuple[str, str]]":
    """Рёбра страницы из выгрузки — с разрешением ветвей (см. граф)."""
    return graph_from_wires(parse_page_wires(text))


def pairs_from_wires(
        wires: "List[Tuple[str, str, str]]") -> "List[Tuple[str, int, str, int]]":
    """Прямые пары с индексами портов: (источник, out, приёмник, in).

    Только провода, у которых источник — блок (`src = "block:out:N"`). Ветвь
    (`src = "wireName:K"`) пропускается: K — точка съёма с линии, а не порт
    источника, и выравнивание по ней поставило бы выход источника под
    случайную точку маршрута. Индексы N — те же, что у COM-адресации портов:
    живой замер 06.10.2026 — у провода с `dst = "LangBlock_0:in:0"` конец
    сошёлся по координате с первым входом блока. Незнакомый формат адреса
    пропускается, а не угадывается: пара с выдуманным индексом сдвинула бы
    блок по ложной цели.
    """
    pairs: "List[Tuple[str, int, str, int]]" = []
    for _name, src, dst in wires:
        src_block, out_sep, out_index = src.partition(":out:")
        dst_block, in_sep, in_index = dst.partition(":in:")
        if not out_sep or not in_sep:
            continue
        if not (out_index.isdigit() and in_index.isdigit()):
            continue
        pairs.append((src_block, int(out_index), dst_block, int(in_index)))
    return pairs


def parse_page_pairs(text: str) -> "List[Tuple[str, int, str, int]]":
    """Прямые пары из выгрузки (см. пары из записей проводов)."""
    return pairs_from_wires(parse_page_wires(text))


@mcp.tool(title="Выгрузить текст модели", annotations={"readOnlyHint": False})
@runtime.com_threaded
def export_model_text() -> str:
    """Выгрузить модель текущей страницы проекта в декларативный текст.

    Так читается то, чего COM не отдаёт: концы линий (какие блоки соединены),
    адреса ветвей, вложенные страницы субмоделей целиком и скрипт самой
    страницы. Для сборки модели из текста обратно служит `import_model_text`.

    **Порядок работы.** Инструмент ставит тело контура в текущую страницу
    (прежний скрипт возвращается на место), запускает расчёт на несколько шагов
    и читает файл выгрузки из каталога результатов. Модельное время при этом
    сдвинется (как после `step`) — если модель считает. На несчитающей модели
    выгрузка **всё равно удаётся**: `savemodeltofile` пишется из секции
    `initialization`, поэтому текст приходит полным, а ответ начинается со
    строки состояния — «модель не считает» (живое наблюдение 01.10.2026:
    субмодель со стоящим расчётом выгрузилась целиком). У **отдельно
    открытой субмодели** с входными порт-блоками «не считает» — штатное
    состояние: их входы питаются извне при инстанцировании (замер
    09.10.2026), и ответ это называет, чтобы состояние не читалось дефектом
    модели. Отказ здесь — только когда тело не отработало вовсе
    (`not-compiled`, `aborted`).

    **Что в ответе.** Текст выгрузки: свойства страницы (`x_center`), объекты
    записями вида `Имя: (type = "Класс", points = […], свойства)`, провода
    (`type = "wire"`, `src`, `dst`) и вложенные `subsystem:`. Объём ограничен,
    как и у `read_output_file`: при превышении текст обрезается с пометкой.
    Поле `script` страницы содержит временный скрипт контура — не скрипт проекта
    (прежний возвращается на место после прогона).

    **Подписи идентичности — перед текстом.** Две вещи текстом не читаются
    (issue #153), и ответ несёт их отдельными строками, а не правкой текста
    (текст — вход `import_model_text`): «Ячейки памяти» — блоки
    «В память»/«Из памяти» и их `PortNames` (имя переменной; пары сходятся по
    имени — номера не парные, замер 13.10.2026) и «Ветви» — ветвь названа
    адресом приёмника, родитель — концами линии (автоимена проводов в
    выгрузке неразличимы, замер 08.10.2026). Подписи вспомогательные: их
    недоступность не отменяет выгрузку, но называется строкой; собираются они
    **отдельным прогоном контура** после выгрузки — в общем теле сбой подписи
    увёл бы исход в `aborted`, и выгрузка была бы отменена (находка ревью
    PR #154). На странице без проводов прогон подписи не запускается: ветвей
    без линий не бывает — лишнего контура нет.
    """
    page = session.ensure_project().get_current_page()
    blocks: "List[Block]" = []
    signatures_error = ""
    try:
        blocks = page.get_blocks()
    except Exception:                                         # noqa: BLE001
        signatures_error = ("Подписи ячеек памяти и ветвей не собрались: "
                            "перечислить блоки страницы не удалось.\n")
    text, truncated, outcome, text_path = page_export_text()
    notes = ""
    if not signatures_error:
        try:
            notes = _identity_notes(blocks,
                                    _parse_wire_probe(_wire_probe_lines()))
        except Exception:                                     # noqa: BLE001
            notes = ("Подписи ячеек памяти и ветвей не собрались "
                     "(внутренняя ошибка чтения) — текст выгрузки полный.\n")
    note = (
        f"\n… текст обрезан по пределу {sandbox.MAX_OUTPUT_BYTES} байт"
        if truncated
        else ""
    )
    # Состояние — ДО текста: он бывает в сотни строк, и предупреждение не
    # должно тонуть в его конце. Стоящий расчёт выгрузке не мешает (файл
    # пишется из `initialization`), но агент решает по ответу, что делать
    # дальше, и обязан видеть, что модель не считает.
    head = ""
    if outcome.kind == OUTCOME_MODEL_NOT_RUNNING:
        head = (describe_outcome(outcome, what="Выгрузка")
                + " Если это отдельно открытая субмодель с входными "
                  "порт-блоками — состояние штатное: такие входы питаются "
                  "извне при инстанцировании (замер 09.10.2026). Текст при "
                  "этом полный: savemodeltofile пишется из секции "
                  "`initialization`, а не из шагов расчёта.\n")
    return (f"{head}{signatures_error}{notes}"
            f"Текст модели (файл {text_path}):\n{text}{note}")


#: Классы ячеек беспроводной передачи сигналов: имя переменной живёт в их
#: `PortNames` (ответ владельца 05.10.2026; живые замеры 05–06.10 и 13.10.2026
#: — `getpropasstring(id, "PortNames")` вернул `ToMem_4=[#RA402]` и т. п.).
#: Выгрузка этих имён не несёт: блоки видны автоименами `ToMem_N`/`FromMem_M`,
#: а номера пар не совпадают (`ToMem_4` читается `FromMem_1` — находка fdd003
#: 13.10.2026), поэтому связать пару можно только по имени.
MEMORY_CELL_CLASSES = ("В память", "Из памяти")

#: Маркер конца строк подписи о ветвях: без него обрыв тела контура выглядел
#: бы как «ветвей нет».
WIRE_PROBE_DONE = "WDONE"

#: Точка в печати языка: «92+64i» (скобки и пробелы допускаются). Дробная
#: часть допускается намеренно: живого формата печати у нас нет (в
#: `check_model` он тоже читается с дробными), а целочисленный шаблон на
#: «92.5+64i» ловил бы «5+64i» и давал чужую клетку (находка ревью PR #154).
_POINT_CELL_RE = re.compile(
    r"\(?\s*(-?\d+(?:\.\d+)?)\s*([+-])\s*(\d+(?:\.\d+)?)i\s*\)?")


def _wire_probe_body(wire_ids: "List[int]") -> str:
    """Хвост тела контура: концы и родитель каждой линии — строками `W|…`.

    Развёрнуто по id, известным из COM (`page.get_wires`), — как в
    `check_model._check_script`: циклы языка в контуре применяются только в
    проверенных формах, и один оператор на линию их не требует. Функции —
    измеренные: `getwirestartpointcoord`/`getwireendpointcoord`
    (`check_model_layout`), `getparentwireid`/`getparentwirenodeindex`
    (`audit_routing`). Завершает строки маркер `WIRE_PROBE_DONE` — по нему
    `_parse_wire_probe` отличает полную подпись от оборванной. Маркер пишется
    и при пустом списке линий: без него страница без проводов давала ложный
    обрыв подписи (находка ревью PR #154).
    """
    lines = [
        f'writelnutf8(fid, "W|{wire_id}|" '
        f"+ getwirestartpointcoord({wire_id}) "
        f'+ "|" + getwireendpointcoord({wire_id}) '
        f'+ "|" + inttostr(getparentwireid({wire_id})) '
        f'+ "|" + inttostr(getparentwirenodeindex({wire_id})));'
        for wire_id in wire_ids
    ]
    lines.append(f'writelnutf8(fid, "{WIRE_PROBE_DONE}");')
    return "\n".join(lines) + "\n"


def _wire_probe_lines() -> "Optional[List[str]]":
    """Строки подписи о ветвях — отдельным прогоном контура.

    Прогон отдельный от выгрузки намеренно (находка ревью PR #154): в общем
    теле сбой подписи (например, отказ среды на устаревшем id) уводил исход в
    `aborted`, и `refuse_contour_failure` отменял выгрузку — хотя её текст к
    тому моменту уже записан. Здесь любой сбой (не тот исход или отказ моста)
    становится `None` — «не прочитано» в ответе, — а выгрузка живёт.

    Пустой список линий сбоем **не** является — это «ветвей нет»: провода
    на странице отсутствуют, и прогон не запускается вовсе.
    """
    try:
        page = session.ensure_project().get_current_page()
        wire_ids = [wire.id for wire in page.get_wires()]
    except Exception:                                         # noqa: BLE001
        return None
    if not wire_ids:
        return []
    try:
        outcome, _restored = run_contour(
            _wire_probe_body(wire_ids),
            failed="подпись о ветвях не собралась")
    except ToolError:
        return None
    if outcome.kind in (OUTCOME_OK, OUTCOME_MODEL_NOT_RUNNING):
        return outcome.lines
    return None


def _parse_wire_probe(
        lines: "Optional[List[str]]"
) -> "Optional[Dict[int, Tuple[str, str, int, int]]]":
    """Подпись о ветвях из строк тела: None — подписи нет или тело оборвалось.

    Формат строки — `W|<id>|<начало>|<конец>|<родитель>|<узел>`. `None` — не
    «ветвей нет»: без маркера пустую подпись не отличить от оборванной, и
    выдавать второе за первое нельзя (`_wire_probe_lines` возвращает `None`
    и на сбой прогона). Пустой список — не оборванный прогон, а «проводов не
    было» (прогон не запускался): это пустая подпись.
    """
    if lines is None:
        return None
    if not lines:
        return {}
    probe: "Dict[int, Tuple[str, str, int, int]]" = {}
    done = False
    for line in lines:
        text = line.strip()
        if text == WIRE_PROBE_DONE:
            done = True
            continue
        parts = text.split("|")
        if len(parts) != 6 or parts[0] != "W":
            continue
        try:
            probe[int(parts[1])] = (parts[2], parts[3],
                                    int(parts[4]), int(parts[5]))
        except ValueError:
            continue
    if not done:
        return None
    return probe


def _point_cell(text: str) -> "Optional[Tuple[int, int]]":
    """Клетка координаты точки из строки языка («92+64i», «-160-992i»).

    Дробные округляются к целому: клетка — общий язык подписи и карты портов,
    а порты COM отдаёт целыми.
    """
    match = _POINT_CELL_RE.search(text)
    if not match:
        return None
    y = float(match.group(3))
    if match.group(2) == "-":
        y = -y
    return (round(float(match.group(1))), round(y))


def _ports_of(block: Block, kind: str) -> "List[Tuple[int, Port]]":
    """Порты блока одного вида — (индекс, порт).

    Перебор — до общего числа портов (`get_port_count`): запрос за границей
    вида библиотечные `get_in_port`/`get_out_port` проводят через
    `BlockAfterEdit` (пересоздание портов) — это сцена-правка в инструменте
    чтения, и лишних итераций здесь не делаем (находка ревью PR #154). Один
    такой запрос на блок-вид остаётся — он внутри самой библиотеки, — и
    платится только когда ветви на странице есть (`_identity_notes`).
    """
    ports: "List[Tuple[int, Port]]" = []
    take = block.get_in_port if kind == "in" else block.get_out_port
    for index in range(block.get_port_count()):
        try:
            ports.append((index, take(index)))
        except Exception:                                     # noqa: BLE001
            break
    return ports


def _register_ports(addressing: "Dict[Tuple[int, int], str]",
                    block: Block, name: str) -> None:
    """Внести порты одного блока в адресацию клеток: координата → «блок:in:N».

    Адреса — в синтаксисе выгрузки (индексы те же, что у `pairs_from_wires`):
    по ним подпись о ветвях называет родителя, а клиент находит запись в
    тексте. Совпавшая клетка у двух разных портов адреса не получает («?») —
    угадывать адресат нельзя.
    """
    for kind in ("in", "out"):
        for index, port in _ports_of(block, kind):
            try:
                coords = port.get_coords()
            except Exception:                                 # noqa: BLE001
                continue
            cell = (round(float(coords[0])), round(float(coords[1])))
            address = f"{name}:{kind}:{index}"
            if cell in addressing and addressing[cell] != address:
                addressing[cell] = "?"
            else:
                addressing[cell] = address


def _cells_line(cells: "List[str]", unread: "List[str]") -> str:
    """Строка подписи ячеек памяти из собранных значений (пусто — нет ячеек)."""
    if not cells and not unread:
        return ""
    line = "Ячейки памяти (PortNames): " + "; ".join(cells)
    if unread:
        suffix = f"не прочиталось у: {', '.join(unread)}"
        line = f"{line}; {suffix}" if cells else f"Ячейки памяти: {suffix}"
    return line + "\n"


def _branch_lines(probe: "Optional[Dict[int, Tuple[str, str, int, int]]]",
                  addressing: "Dict[Tuple[int, int], str]") -> str:
    """Строки подписи о ветвях: ветвь — адресом приёмника, родитель — концами.

    Ветвь адресует родителя именем (`src = "MBTYWire:0"`), а у проводов от COM
    имя одно на всех (замер 08.10.2026; находка fdd003 13.10.2026) — по имени
    родитель не находится. Здесь родитель называется своими концами в
    синтаксисе выгрузки: клиент находит родительскую запись по ним. Конец, не
    сошедшийся с портом, печатается «?» — это и признак испорченной геометрии
    (запечённые импортом маршруты — см. `import_model_text`). Пустой сегмент
    ветвления (конец `0+0i`, `wires.EMPTY_WIRE_END`) пропускается: строка о
    нём была бы строкой о невидимой пустышке (находка ревью PR #154).
    """
    if probe is None:
        return ("Ветви: не прочитано — прогон подписи не отдал строк "
                "(обрыв контура или отказ); родителя ищите в GUI.\n")
    branches = [(wire_id, data) for wire_id, data in sorted(probe.items())
                if data[2] != 0 and data[1] != EMPTY_WIRE_END]
    if not branches:
        return ""

    def address(point: str) -> str:
        cell = _point_cell(point)
        if cell is None:
            return "?"
        return addressing.get(cell, "?")

    parts: "List[str]" = []
    for _wire_id, (_start, end, parent_id, node) in branches:
        parent = probe.get(parent_id)
        src = address(parent[0]) if parent else "?"
        dst = address(parent[1]) if parent else "?"
        parts.append(f"dst={address(end)} — на линии src={src} → dst={dst} "
                     f"(узел {node - 1})")
    lines = ["Ветви (родитель назван концами линии — автоимена в выгрузке "
             "неразличимы):"]
    lines.extend(f"  {part}" for part in parts)
    return "\n".join(lines) + "\n"


def _identity_notes(blocks: "List[Block]",
                    probe: "Optional[Dict[int, Tuple[str, str, int, int]]]"
                    ) -> str:
    """Подписи идентичности — одним обходом блоков.

    Имя блока читается один раз на блок — и им же подписываются его порты в
    адресации, — а адресация строится, только если ветви на странице есть:
    перебор портов ходит в COM, и на странице без ветвей это была бы плата ни
    за что (находки ревью PR #154 — двойное чтение имён и жадная адресация).
    """
    cells: "List[str]" = []
    unread: "List[str]" = []
    needs_ports = probe is not None and any(
        data[2] != 0 and data[1] != EMPTY_WIRE_END for data in probe.values())
    addressing: "Dict[Tuple[int, int], str]" = {}
    for block in blocks:
        try:
            name = block.get_name()
        except Exception:                                     # noqa: BLE001
            continue
        try:
            is_cell = block.class_name in MEMORY_CELL_CLASSES
        except Exception:                                     # noqa: BLE001
            is_cell = False
        if is_cell:
            try:
                raw = block.get_property("PortNames")
            except Exception:                                 # noqa: BLE001
                unread.append(name)
            else:
                value = " ".join(str(raw).split())
                cells.append(f"{name} = {value}" if value
                             else f"{name} = (пусто)")
        if needs_ports:
            _register_ports(addressing, block, name)
    return _cells_line(cells, unread) + _branch_lines(probe, addressing)


def _wire_count() -> Optional[int]:
    """Число линий текущей страницы или `None`, если перечислить не удалось."""
    try:
        return len(session.ensure_project().get_current_page().get_wires())
    except Exception:                                          # noqa: BLE001
        return None


#: Имя записи текста: `Имя: (` в начале строки — так выглядят и объекты, и
#: провода (выгрузка). Скан по строкам — не разбор текста (философия
#: `_duplicate_record_names`): он питает предупреждение, а не управляет
#: сборкой, поэтому приблизительность ему прощается, а молчание — нет.
_RECORD_NAME_RE = re.compile(r"\s*([A-Za-z_][\w]*)\s*:\s*\(")


def _text_wire_roles(model_text: str) -> "Tuple[bool, bool]":
    """Роли проводов текста: (есть провода, есть провода на блоки этого текста).

    Развилка предупреждения — по ссылкам, а не по соседству: мусорную
    геометрию запекает трассировка по габаритам ТОЛЬКО ЧТО добавленных
    блоков, поэтому дефект называется прямо лишь у проводов, чьи концы — на
    блоках этого же текста. Дозагрузка блока к уже расставленной модели
    (провода между существующими блоками) чужой геометрией не пугается —
    находка ревью PR #150: прежний скан «есть и объекты, и провода рядом»
    срабатывал на ней как на дефекте. Имена концов — как в адресах
    `src`/`dst`; ветви разрешаются по родителю (`graph_from_wires`).
    """
    wires = parse_page_wires(model_text)
    if not wires:
        return False, False
    wire_names = {name for name, _src, _dst in wires}
    objects: "set[str]" = set()
    for line in model_text.splitlines():
        match = _RECORD_NAME_RE.match(line)
        if match:
            objects.add(match.group(1))
    objects -= wire_names
    same_text = any(src in objects or dst in objects
                    for src, dst in graph_from_wires(wires))
    return True, same_text


def _trace_note(before: Optional[int], after: Optional[int],
                roles: "Tuple[bool, bool]") -> str:
    """Напоминание о геометрии добавленных линий: что с ней будет и что делать.

    Маршрут импортированной линии среда запекает при создании — до пересчёта
    габаритов только что добавленных блоков (замеры 04–06.10.2026), и у
    проводов на блоки этого же текста он выходит мусорным и не перестраивается
    ничем (живое воспроизведение 10.10.2026). Поэтому ответ различает случаи
    по ролям проводов (`_text_wire_roles`): у проводов на блоки этого же
    текста дефект называется прямо, а канон сборки — `connect` после импорта
    блоков (живо проверен 10.10.2026; отдельные тексты — второй путь, и он не
    для моделей с памятью); у проводов на существующие блоки — предупреждение
    о запекании и проверка выгрузкой. Прежний текст ответа звал
    «`layout_place` проложит линии» и для запечённой геометрии был неверен — с
    ним клиент шёл чинить нормализацией то, что ею не чинится (замечание
    fdd002, 10.10.2026).

    Считается **прирост** линий (чтения до и после контура), а не общее
    число: прежде по одному счётчику ответ утверждал «после импорта они не
    трассированы» про все линии страницы, включая уже проложенные чужие
    (находка ревью 02.10.2026). Ошибка чтения не превращается в отказ: модель
    уже импортирована, и отказ после изменения состояния выглядел бы как
    «импорт не удался».
    """
    if before is None or after is None:
        return ("ВНИМАНИЕ: перечислить линии страницы не удалось — "
                "ортогональность проверьте в GUI.")
    added = after - before
    if after == 0:
        return "Линий связи на странице нет — трассировать нечего."
    if added <= 0:
        return (f"Линии связи: {after}; новых импорт не добавил — "
                f"существующие линии не затронуты.")
    wires_in_text, same_text_wires = roles
    if wires_in_text and same_text_wires:
        return (
            f"Линии связи: +{added} (всего {after}) — провода из текста, и "
            f"часть из них — на блоки этого же текста: маршруты таких линий "
            f"среда запекает мусорными — звенья вида (-160,-992) вне рабочей "
            f"области, одинаковые при любых позициях блоков (живое "
            f"воспроизведение 10.10.2026). Запечённый маршрут не "
            f"перестраивается ничем: ни `layout_place`/`NormalizeWire` "
            f"(заполненный маршрут нормализация не перестраивает — мусорные "
            f"звенья остаются), ни "
            f"`save_project` + `reload_project`; адреса концов корректны — "
            f"испорчена геометрия, не связность. Блоки расставит `layout_place` "
            f"без аргументов, но эти маршруты он не починит: их пересчитывает "
            f"только пересоздание линий — снятие и `connect` заново (живой "
            f"замер 10.10.2026: импорт только блоков → `connect` → перерисовка "
            f"→ маршруты корректны) либо сборка в GUI. Модели с блоками "
            f"памяти — исключение: их собирайте ОДНИМ текстом (замер "
            f"08.10.2026: последовательные импорты ломают расчёт), а провода "
            f"такого текста чините пересозданием.")
    if wires_in_text:
        return (
            f"Линии связи: +{added} (всего {after}) — провода из текста; "
            f"ссылок на блоки этого же текста в них не видно (именно на таких "
            f"ссылках запекается мусорная геометрия — «вокруг блоков в "
            f"(0,0)»). Маршрут среда считает при создании сама — точки текста "
            f"игнорируются (замеры 04–06.10.2026); линия, пришедшая без "
            f"маршрута (`points = []`), дорисовывается "
            f"`layout_place(normalize_only=True)`; блоки, добавленные "
            f"текстом, расставит `layout_place` без аргументов. Запечённый "
            f"мусорный маршрут (звенья вдали от схемы) не пересчитывается — "
            f"лечится пересозданием линии; проверка — выгрузкой (`points`).")
    return (
        f"Линии связи: +{added} (всего {after}); записей проводов в тексте "
        f"не видно, но линии добавились — геометрию им среда запекает при "
        f"создании, до перерисовки, и заполненный маршрут нормализация не "
        f"пересчитывает — проверьте выгрузкой или снимком.")


def _duplicate_record_names(model_text: str) -> List[Tuple[str, int]]:
    """Имена записей текста, встречающиеся больше одного раза: (имя, число).

    Записи модели — поля record-литерала (`Имя: ( … )`). Среда **не
    компилирует повтор имени записи**: текст с двумя `Wire:` отвергается
    целиком (живой замер 08.10.2026 — исход not-compiled, ни один объект не
    создан), и ошибка видна только в окне редактора SimInTech. При этом дубли
    порождает и сама среда: `export_model_text` печатает ветви под одним
    автоименем (`MBTYWire` ×N), так что круг «выгрузка → импорт» спотыкается
    об это штатно.

    Повтор имени в **разных** субмоделях этим сканом тоже считается — потому
    находка идёт «первой причиной к проверке» при not-compiled, а не
    приговором: текст — не наш формат, и полный разбор его грамматики
    сознательно не делается (см. докстринг инструмента). Замер 08.10.2026:
    две субмодели, в каждой запись `pin1`, — импорт **прошёл**; повтор в
    одной записи (два `Wire` на верхнем уровне) — not-compiled.
    """
    counts: Dict[str, int] = {}
    for line in model_text.splitlines():
        match = _RECORD_NAME_RE.match(line)
        if match:
            name = match.group(1)
            counts[name] = counts.get(name, 0) + 1
    return sorted(((name, count) for name, count in counts.items() if count > 1),
                  key=lambda item: (-item[1], item[0]))


@mcp.tool(title="Собрать модель из текста", annotations={"readOnlyHint": False})
@runtime.com_threaded(mutates_project=True)
def import_model_text(model_text: str) -> str:
    """Собрать объекты модели из декларативного текста.

    Текст — того же формата, что возвращает `export_model_text`: записи
    `Имя: (type = "Класс", points = […], свойства)` и провода (`type = "wire"`
    с `src`/`dst`). Объекты добавляются в текущий контейнер; **старые не
    трогаются** — `createmodel` дополняет модель (вендор подтвердил
    2026-09-28): их координаты и ручная раскладка переживают повторные
    импорты (контракт #24 п.6, наблюдение 01.10.2026 — правки после ручной
    доводки её не сдвинули).

    **Текст — это код, а не данные.** Форма `const model : ( … );` — часть
    встроенного языка, и текст принимает компилятор SimInTech, а не сервер:
    инструмент не разбирает его грамматику и не проверяет по списку разрешённого.
    Так сделано намеренно: свой парсер языка неизбежно был бы неполным, а
    неполный разбор молча ломал бы корректные модели — ровно тот класс отказа,
    против которого весь остальной контур (среда об ошибках скрипта молчит).
    Поэтому текст берут из `export_model_text` своего же проекта или собирают по
    образцу, а не из чужого источника.

    **Выгрузку можно подавать как есть.** Текст, который вернул
    `export_model_text` (вместе с обрамляющими скобками, свойствами страницы и
    полем `script`), принимается без правки: замер 2026-09-29 — объекты
    создаются, вердикт `ok`. Провода из такого текста получат запечённую
    геометрию импорта (см. границы `createmodel` ниже). Прежде это не
    работало по нашей вине: выгрузка оборачивалась в `const model : ( … )`
    **второй раз**, и среда молча не компилировала скрипт (двойная
    вложенность скобок).

    **Кавычки.** Внутри текста кавычка задаётся `chr(34)`: удвоение `""` в этой
    сборке даёт пустую строку, а обратный слэш не экранирует. Текст с удвоенными
    кавычками при этом выглядит правдоподобно, объектов не создаёт и сообщений
    не оставляет — заметить это можно только по отчёту об изменениях.

    **Границы `createmodel` (живые замеры 03.10 и 10.10.2026).** Текст
    собирают строго по форме выгрузки — четыре вещи ломаются молча или со
    сбивающим сообщением:

    - **Трейлинг-запятая после последнего свойства — `not-compiled`.** `points
      = […],` перед `)` даёт «Символ , не может быть использован в выражении»,
      причём указатель — на строку `createmodel(…)` в обёртке. Канон: последнее
      свойство — без запятой (как в выгрузке).
    - **Ветвление от выхода текстом не воспроизводится.** Второй провод из того
      же выхода «пришивается» цепочкой: в выгрузке он становится
      `src = "tw1:0"` — ссылкой на провод. Провода к одному входу (разные
      источники) работают. Поэтому импорт — «один провод на выход», а ветвления
      стройте `connect` (он делает их правильно). Это же ограничение —
      у round-trip: выгрузку с ветвлением повторный импорт воспроизведёт
      цепочкой, а не ветвлением.
    - **Провода из того же текста, что их блоки, — дефект геометрии.**
      Среда трассирует импортированные провода сама (точки текста
      игнорируются — замеры 04–06.10.2026) — в момент создания, когда
      габариты только что добавленных блоков ещё не пересчитаны: маршрут
      выходит «вокруг блоков в (0,0)» — звенья вида `(-160,-992)` вне
      рабочей области, бит-в-бит одинаковые при любых позициях блоков
      (живое воспроизведение 10.10.2026: боевая модель на стенде FDD002 и
      минимальная пара блоков у нас — и `points=[]`, и явные точки payload
      на результат не влияют: выходят те же звенья). То же — у проводов
      **внутри** импортируемой субмодели: замер 10.10.2026 — линия с
      `points=[]` между двумя её новыми блоками получила маршрут
      `(288,88),(288,156),(216,156),(216,224)` при портах (256,88) →
      (280,88). Адреса концов при этом
      корректны — испорчена геометрия, не связность. Запечённый маршрут не
      перестраивается ничем: ни `layout_place`/`NormalizeWire` (замер
      10.10.2026: предельное вмешательство нормализации — дотянуть конец к
      колонке приёмника; мусорные звенья остаются), ни `save_project` +
      `reload_project` (замеры там же); чинится только пересозданием линий —
      в GUI или снятием и сборкой заново (такие линии `disconnect_wire` не
      читает, `findstartport` = 0; работает снятие по порту:
      `getportwireid` + `removeprimitiv`, замер 10.10.2026 — затем `connect`
      и `normalize_only`, маршрут корректный и переживает `save_project` +
      переоткрытие). Канон сборки — провода **`connect`-ом после импорта
      блоков** (живой замер 10.10.2026: импорт блоков → `connect` →
      перерисовка переносом → маршруты корректны); отдельные тексты (блоки →
      при необходимости `save_project` и переоткрытие → провода) — второй
      путь, и он **не для моделей с памятью** (их собирают ОДНИМ текстом —
      см. ниже; провода такого текста чините пересозданием).
    - **Класс субмодели в тексте — «Субмодель», не `Macro`.** Рабочая форма —
      `type = "Субмодель"` с содержимым во вложенной секции `subsystem:`
      (свойства страницы): импортируется целиком, вместе с внутренними
      блоками (живые замеры 06–08.10.2026 — так пересобраны 9 субмоделей
      sub_TractionHVSupply; подтверждено 10.10.2026 на минимальной). А
      `type = "Macro"` — так выгружается пустая субмодель от
      `createprimitiv(102)`/`inject_submodel_script` — `createmodel` **молча
      игнорирует**: вердикт `ok`, объектов ноль (замер 10.10.2026; с секцией
      `subsystem:` расчёт вдобавок остаётся стоящим, `subsystem: ()` —
      `not-compiled`). Молчание здесь опаснее отказа: импорт «удался», а
      объекта нет.

    **Геометрию добавленных линий запекает среда при импорте.** Точки из
    текста игнорируются: маршрут среда считает сама в момент создания, до
    пересчёта габаритов добавленных блоков (замеры 04–06.10.2026), и у
    проводов на блоки из этого же текста он выходит мусорным (см. границы
    `createmodel` выше). Пустые маршруты нормализация заполняет (так
    приходят линии, созданные `connect` после импорта, и часть проводов
    самого текста — живой замер 04.10.2026: 18 из 132), а испорченные не
    перестраивает: запечённые звенья переживают и её, и переоткрытие (замер
    10.10.2026). Ответ различает случаи по ссылкам проводов
    (`_text_wire_roles`: концы на блоки этого же текста или на существующие)
    и называет канон сборки; прироста нет — ответ скажет и это, а не
    припишет импорту чужие линии.

    **Пины блоков «Язык программирования» импорт не пересобирает.**
    `createmodel` их не генерирует (замер 01.10.2026: у свежего PL-блока один
    дефолтный вход, а провода к остальным пинам создаются половинками молча),
    а автоматический обход с `reinitlangblock` **сознательно не делается**:
    пересборка пинов измеренно неполна для объявлений с размером
    (`a[3]: array` даёт два входа вместо трёх, замер 02.10.2026), и цикл
    затронул бы уже настроенные блоки. Если после импорта у PL-блока нужны
    пины — доведите его осознанно: `set_block_script` (перезапись скрипта тем
    же текстом = «setprop + reinitlangblock») или `reinitlangblock` в
    `run_page_script`; провода-половинки досоединяет `connect` штатно.
    Имена объектов из текста креатемодел приводит к **нижнему регистру**
    (`Trigger` → `trigger`, замер 03.10.2026), а `connect` **регистрозависим**
    («блок не найден» на исходное имя) — адресуйте блоки по фактическим именам
    из ответа импорта или `list_blocks`.

    **Порядок работы** как у выгрузки: тело идёт в секцию `initialization`,
    расчёт делает несколько шагов, прежний скрипт страницы возвращается на
    место, изменения модели живут в памяти до `save_project`.

    **Модели с памятью собирайте ОДНИМ текстом.** Последовательные импорты
    (`createmodel` поверх уже созданных блоков «В память»/«Из памяти»)
    ломают расчёт: после второго-третьего импорта вердикт становится «модель
    не считает — неподключённый вход», хотя данные целы (живые замеры
    08.10.2026, 2.26.9.29: на одном стенде слом наступил на третьем импорте,
    на другом — на втором; тем же составом, залитым **одним** текстом,
    модель считается). Достраивать такую модель по частям нельзя —
    пересоберите её одним импортом (выгрузка даёт текст целиком).

    Args:
        model_text: декларативный текст модели (как из `export_model_text`).
    """
    if not model_text.strip():
        raise ToolError(
            "текст модели пуст: собирать нечего. Пустой текст — не «ничего не "
            "сделает»: он означает, что на стороне клиента содержимое потеряно, "
            "и молчание здесь скрыло бы это.")
    dups = _duplicate_record_names(model_text)
    roles = _text_wire_roles(model_text)
    wires_before = _wire_count()
    before = object_names()
    outcome, restored = run_contour(
        build_import_model_text_body(model_text),
        failed="собрать модель из текста не удалось")
    try:
        refuse_contour_failure(
            outcome, failed="сборка модели",
            aborted_hint=("Часть объектов могла создаться до обрыва — "
                          "сверьте `list_blocks`/`list_wires`; прежний "
                          "скрипт страницы возвращён."))
    except ToolError as exc:
        # Диагноз not-compiled — самый дорогой: текст ошибки виден только в
        # окне редактора SimInTech. Повтор имени записи — единственная
        # причина, которую можно назвать по тексту, и частая на круге
        # «выгрузка → импорт» (среда печатает ветви одним автоименем).
        if outcome.kind == OUTCOME_NOT_COMPILED and dups:
            names = ", ".join(f"`{name}` ({count}×)" for name, count in dups[:3])
            more = f" и ещё {len(dups) - 3}" if len(dups) > 3 else ""
            raise ToolError(
                f"{exc} Возможная причина названа: в тексте повторяются "
                f"имена записей — {names}{more}. Повтор имени записи среда "
                f"не компилирует (первая причина к проверке при "
                f"not-compiled); уникализируйте имена, поправив и ссылки "
                f"`src=\"<имя>:0\"` — за образец возьмите выгрузку свежего "
                f"проекта."
            ) from exc
        raise
    after = object_names()
    wires_after = _wire_count()
    return (
        f"Модель собрана из текста.\n"
        f"{describe_outcome(outcome, what='Вердикт')}\n"
        f"{change_report(before, after, restored)}\n"
        f"{_trace_note(wires_before, wires_after, roles)}"
    )
