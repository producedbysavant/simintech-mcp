"""Правила владельца, общие для инструментов и ресурсов.

Здесь одно место для правила ветвления и правила размеров блоков: копии
чисел в инструментах и руководстве разошлись бы при первой правке.
`connect_branch` предупреждает о ветвлении при создании ветви,
`audit_routing` проверяет его по странице; фиты, `set_block_size`,
`check_model_layout` и `simintech://guides/block-sizing` читают размеры
отсюда.
"""

from __future__ import annotations

from collections.abc import Iterable

#: Линий в узле ветвления — не больше трёх (замечание владельца 07.10.2026:
#: «в 1 точку не может приходить больше 3 линий»). Сквозная линия у узла одна
#: — она даёт два противоположных луча, — поэтому три линии могут сойтись
#: «плюсом» из четырёх лучей: это норма, а не нарушение (уточнение владельца
#: 08.10.2026). Четыре линии в узле — «звезда»; живой замер 08.10.2026: три
#: `connect_branch` от одного выхода сели в один узел — родитель и три ветви.
MAX_NODE_LINES = 3


# ─── Размеры блоков с входными контактами ─────────────────────────

#: Высота одной строки входного контакта: 16 px (2 квадратика разметки).
#: Порт стоит посередине строки, поэтому сверху и снизу остаётся по 8 px.
#: Правило владельца: высота блока = 16 px на входной контакт. Живой замер
#: 23.10.2026 (2.26.9.29): у пяти nport-классов при 4 входах высота 64 даёт
#: шаг портов 16 и поля 8 / 8.
PORT_ROW_HEIGHT = 16

#: Поле до края блока для крайнего входного контакта: половина строки.
PORT_MARGIN = PORT_ROW_HEIGHT // 2

#: Штатная ширина блоков с переменным числом входов. Подгонка не сужает
#: блок, расширенный вручную: ширина растёт до этого значения, но не падает.
NPORT_BLOCK_WIDTH = 32

#: Имя параметра числа входов у nport-классов.
NPORT_PARAM = "nport"

#: Классы, у которых `nport` задаёт число входных контактов, а выход один:
#: «Мультиплексор» (живой замер 08.10.2026), «Оператор И», «Оператор ИЛИ»,
#: «Перемножитель», «Минимум по входам» (живой замер 23.10.2026).
#: Высота = число входов × PORT_ROW_HEIGHT; ширина не уже NPORT_BLOCK_WIDTH.
NPORT_SIZE_CLASSES = (
    "Мультиплексор",
    "Оператор И",
    "Оператор ИЛИ",
    "Перемножитель",
    "Минимум по входам",
)

#: Классы с параметром `nport`, но вне правила высоты. У «Внешней DLL»
#: несколько выходов, а `nport` по умолчанию 0; у «Минимума по всем
#: элементам вектора» `nport` - размерность вектора, а не число контактов.
NPORT_OTHER_CLASSES = (
    "Внешняя DLL",
    "Минимум по всем элементам вектора",
)

#: Почему класс с `nport` не подчиняется правилу высоты. Тексты руководства
#: собираются из этого словаря, чтобы список классов не дублировался.
NPORT_OTHER_REASONS = {
    "Внешняя DLL": "несколько выходов, nport по умолчанию 0",
    "Минимум по всем элементам вектора": "nport это размерность вектора",
}

#: Классы, чья высота считается по числу входных контактов: субмодель
#: (правило владельца 07.10.2026, выход строки не занимает) и nport-классы.
ROW_HEIGHT_CLASSES = ("Субмодель", *NPORT_SIZE_CLASSES)

#: Классы табличных блоков алгоритма: высота - 16 px на **позицию** таблицы.
#: Позиции считаются по всей таблице, включая пустые заполнители и строки без
#: активных портов (канон владельца 21.11.2026, по `Signal_Block_Vec_0` и
#: `ALG_Vec_0`); строка-заголовок при `fExcludeFirst=1` не считается. Живые
#: замеры: 357 позиций -> 5712, 8 позиций -> 128... (см. `table_positions`).
ALGORITHM_TABLE_CLASSES = ("Вход алгоритма", "Вход алгоритма (векторный)",
                           "Выход алгоритма", "Выход алгоритма (векторный)")


def table_positions(raw: str, header: bool = True) -> int:
    """Число позиций таблицы сигналов по значению `SignalNames`.

    `raw` - свойство `SignalNames` как его отдаёт COM: позиции через CRLF.
    Завершающая пустая строка отбрасывается, строка-заголовок (`header`)
    тоже: канон владельца считает позиции, а не заголовок. Пустые
    заполнители **считаются**: у тестового блока 357 позиций при 112 именах.
    """
    text = (raw or "").replace("\r\n", "\n").replace("\r", "\n")
    parts = text.split("\n")
    if parts and parts[-1] == "":
        parts.pop()
    if header and parts:
        parts.pop(0)
    return len(parts)


def table_height(raw: str, header: bool = True) -> int | None:
    """Высота табличного блока: `16 px` на позицию; пустая таблица - `None`."""
    positions = table_positions(raw, header)
    return PORT_ROW_HEIGHT * positions if positions > 0 else None


#: Классы порт-блоков: высота 16 px на строку сигнала `PortNames`
#: (правило владельца 01.10.2026).
PORT_HEIGHT_CLASSES = ("Порт входа", "Порт выхода")

#: Классы блоков памяти: ширина по подписям `PortNames` (замер 07.10.2026).
MEMORY_WIDTH_CLASSES = ("В память", "Из памяти")


def grid_height(counts: Iterable[int]) -> int | None:
    """Высота блока: `16 px` на порт **большей** стороны.

    Среда раскладывает порты стороны равномерно по всей высоте: при `N`
    портах позиции `H*(2k+1)/(2N)` (живые замеры 14.11.2026: субмодель 3/2
    при H=32 дала входы 5.33/16/26.67 и выходы 8/24; субмодель 4/1 при H=32:
    входы 4/12/20/28 и выход в центре). При `H = 16*N` шаг стороны равен
    16 px, а первый порт стоит на 8 px: сетка 8 px соблюдена.

    **Приоритет - сторона с большим числом портов** (решение владельца
    19.11.2026). Совпадение сетки у обеих сторон требует `H = 16*НОК(N_i)`,
    и у 28/26 это 5824 px: блок высотой в шесть экранов. Поэтому высота -
    `16 * max(N_i)`, а порты меньшей стороны ложатся с шагом
    `16*max/N_min` и мимо сетки; выравнивать их вручную - отдельная задача.

    Это ровно прежнее правило «16 px на контакт», когда сторона одна (nport-
    классы, порт-блоки) или выходов не больше, чем входов.

    Ноль на всех сторонах правила не даёт: у блока без портов проверять
    нечего. Пустой список: `None`.
    """
    live = [int(count) for count in counts if int(count) > 0]
    if not live:
        return None
    return PORT_ROW_HEIGHT * max(live)


def required_height(class_name: str, counts: int | Iterable[int]) -> int | None:
    """Высота блока по правилу: 16 px на вход или строку сигнала.

    `counts` - строки `PortNames` у порт-блоков или числа контактов по
    сторонам у `ROW_HEIGHT_CLASSES` (входы и выходы отдельно: при разном
    числе высота берётся по сетке, см. `grid_height`). Ноль и меньше правила
    не дают: у блока без входов проверять нечего. Класс вне правила - `None`.
    Что считать (`PortNames` или порты) и как отказывать при нечитаемых
    данных, решают вызывающие: у подгонки, проверки и записи размера разные
    тексты и разная цена ошибки.
    """
    if isinstance(counts, int):
        counts = [counts]
    if class_name in PORT_HEIGHT_CLASSES or class_name in ROW_HEIGHT_CLASSES:
        return grid_height(counts)
    return None
