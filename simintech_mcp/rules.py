"""Правила владельца, общие для инструментов и ресурсов.

Здесь одно место для правила ветвления и правила размеров блоков: копии
чисел в инструментах и руководстве разошлись бы при первой правке.
`connect_branch` предупреждает о ветвлении при создании ветви,
`audit_routing` проверяет его по странице; фиты, `set_block_size`,
`check_model_layout` и `simintech://guides/block-sizing` читают размеры
отсюда.
"""

#: Линий в узле ветвления — не больше трёх (замечание владельца 07.10.2026:
#: «в 1 точку не может приходить больше 3 линий»). Сквозная линия у узла одна
#: — она даёт два противоположных луча, — поэтому три линии могут сойтись
#: «плюсом» из четырёх лучей: это норма, а не нарушение (уточнение владельца
#: 08.10.2026). Четыре линии в узле — «звезда»; живой замер 08.10.2026: три
#: `connect_branch` от одного выхода сели в один узел — родитель и три ветви.
MAX_NODE_LINES = 3


# ─── Размеры блоков с входными контактами ─────────────────────────

#: Высота одной строки входного контакта: 16 px (2 квадратика разметки).
#: Порт стоит посередине строки, поэтому сверху и снизу остаётся по 8 px.
#: Правило владельца: высота блока = 16 px на входной контакт. Живой замер
#: 23.10.2026 (2.26.9.29): у пяти nport-классов при 4 входах высота 64 даёт
#: шаг портов 16 и поля 8 / 8.
PORT_ROW_HEIGHT = 16

#: Поле до края блока для крайнего входного контакта: половина строки.
PORT_MARGIN = PORT_ROW_HEIGHT // 2

#: Штатная ширина блоков с переменным числом входов. Подгонка не сужает
#: блок, расширенный вручную: ширина растёт до этого значения, но не падает.
NPORT_BLOCK_WIDTH = 32

#: Имя параметра числа входов у nport-классов.
NPORT_PARAM = "nport"

#: Классы, у которых `nport` задаёт число входных контактов, а выход один:
#: «Мультиплексор» (живой замер 08.10.2026), «Оператор И», «Оператор ИЛИ»,
#: «Перемножитель», «Минимум по входам» (живой замер 23.10.2026).
#: Высота = число входов × PORT_ROW_HEIGHT; ширина не уже NPORT_BLOCK_WIDTH.
NPORT_SIZE_CLASSES = (
    "Мультиплексор",
    "Оператор И",
    "Оператор ИЛИ",
    "Перемножитель",
    "Минимум по входам",
)

#: Классы с параметром `nport`, но вне правила высоты. У «Внешней DLL»
#: несколько выходов, а `nport` по умолчанию 0; у «Минимума по всем
#: элементам вектора» `nport` - размерность вектора, а не число контактов.
NPORT_OTHER_CLASSES = (
    "Внешняя DLL",
    "Минимум по всем элементам вектора",
)

#: Почему класс с `nport` не подчиняется правилу высоты. Тексты руководства
#: собираются из этого словаря, чтобы список классов не дублировался.
NPORT_OTHER_REASONS = {
    "Внешняя DLL": "несколько выходов, nport по умолчанию 0",
    "Минимум по всем элементам вектора": "nport это размерность вектора",
}

#: Классы, чья высота считается по числу входных контактов: субмодель
#: (правило владельца 07.10.2026, выход строки не занимает) и nport-классы.
ROW_HEIGHT_CLASSES = ("Субмодель", *NPORT_SIZE_CLASSES)

#: Классы порт-блоков: высота 16 px на строку сигнала `PortNames`
#: (правило владельца 01.10.2026).
PORT_HEIGHT_CLASSES = ("Порт входа", "Порт выхода")

#: Классы блоков памяти: ширина по подписям `PortNames` (замер 07.10.2026).
MEMORY_WIDTH_CLASSES = ("В память", "Из памяти")
